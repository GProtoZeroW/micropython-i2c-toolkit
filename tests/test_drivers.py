"""Hand-written drivers against fake parts, and the driver registry.

The TMP102, TCA9548A and TMAG5273 tests are generated by their dev notebooks
(``dev_notebooks/drivers_<part>_devNB``) into ``tests/test_<part>.py``.
"""

import pytest

from micropython_i2c import CommandI2CBase, I2CConnection
from micropython_i2c.drivers import DRIVERS, driver_class, registry
from micropython_i2c.drivers.qwiic_relay import QwiicRelay
from micropython_i2c.drivers.shtc3 import SHTC3
from micropython_i2c.drivers.tmp102 import TMP102
from micropython_i2c.drivers.vl53l4cd import VL53L4CD
from micropython_i2c.fakes import FakeBus, FakeRelay, FakeSensirion, fake_vl53l4cd

# --- SHTC3 and the registry -------------------------------------------------------------


def test_shtc3_measure_and_identify():
    bus = FakeBus()
    part = bus.attach(0x70, FakeSensirion([0x6666, 0x8000], CommandI2CBase.crc))
    sht = SHTC3(I2CConnection(bus, 0x70))
    t, rh = sht.measure()
    assert t == pytest.approx(-45 + 175 * 0x6666 / 65536)
    assert rh == 50.0
    assert part.commands[-1] == SHTC3.CMD_SLEEP  # always put back to sleep
    part.words = [0x0807]
    assert sht.identify()


def test_registry_imports_every_driver():
    reg = registry()
    assert set(reg) == set(DRIVERS)
    assert driver_class("TMP102") is TMP102


# --- VL53L4CD and the Qwiic relay --------------------------------------------------------


def test_vl53l4cd_boots_and_reads():
    bus = FakeBus()
    part = bus.attach(0x29, fake_vl53l4cd(distance_mm=456))
    tof = VL53L4CD(I2CConnection(bus, 0x29))
    assert tof.timing_budget == 50
    assert part.regs[0x002D] == 0x12  # init table landed at 0x2D
    tof.start()
    assert tof.read() == 456 and tof.valid and tof.status_name == "valid"
    with pytest.raises(RuntimeError, match="stop"):
        tof.timing_budget = 100
    tof.stop()
    assert any(entry[0] == "rm" and entry[2] == 0x010F for entry in bus.log)


def test_vl53l4cd_rejects_wrong_model_and_flags_invalid():
    bus = FakeBus()
    part = bus.attach(0x29, fake_vl53l4cd(status=4))
    tof = VL53L4CD(I2CConnection(bus, 0x29))
    tof.start()
    tof.read()
    assert not tof.valid and tof.status_name == "sigma warning"
    assert tof.read_valid(tries=3) is None
    part.regs[0x010F] = 0x00
    with pytest.raises(RuntimeError, match="not a VL53L4CD"):
        VL53L4CD(I2CConnection(bus, 0x29))


def test_vl53l4cd_budget_words_fit_registers():
    for ms in (10, 50, 200):
        for word in VL53L4CD.range_config_words(ms, 0x0BB8):
            assert 0 <= word <= 0xFFFF and word & 0xFF <= 0xFF


def test_qwiic_relay():
    bus = FakeBus()
    part = bus.attach(0x18, FakeRelay(version=0x02))
    relay = QwiicRelay(I2CConnection(bus, 0x18))
    assert relay.state is False
    relay.on()
    assert part.closed and relay.state is True
    assert relay.toggle() is False
    relay.state = True
    assert part.closed
    assert relay.firmware_version() == 0x02
