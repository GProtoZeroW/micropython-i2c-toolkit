@pytest.mark.parametrize(
    "name",
    [
        "micropython_i2c",
        "micropython_i2c.devices.sensors",
        "micropython_i2c.devices.sensors.environmental",
        "micropython_i2c.devices.sensors.magnetic",
        "micropython_i2c.devices.sensors.distance",
        "micropython_i2c.devices.drivers",
        "micropython_i2c.devices.muxes",
        "micropython_i2c.sim",
    ],
)
def test_package_imports_with_a_docstring(name):
    mod = importlib.import_module(name)
    assert mod.__doc__ and "Generated by" in mod.__doc__

