def clock_set(clock):
    """Make every timing function use ``clock``; return the previous clock (CPython only).

    Args:
        clock: Any object with ``ticks_us()`` and ``sleep_us(us)``.

    Raises:
        NotImplementedError: On MicroPython.
        TypeError: If ``clock`` lacks ``ticks_us`` or ``sleep_us``.
    """
    global _clock
    if _MICROPYTHON:
        raise NotImplementedError("the clock is fixed on MicroPython")
    for name in ("ticks_us", "sleep_us"):
        if not callable(getattr(clock, name, None)):
            raise TypeError("clock {!r} has no {}() method".format(clock, name))
    previous, _clock = _clock, clock
    return previous

