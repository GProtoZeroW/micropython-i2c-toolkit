class FakeQwiicRelay:
    """SparkFun Qwiic Single Relay: one-byte commands, status read as a command byte.

    Args:
        version: The firmware version byte (command ``0x04``).

    Attributes:
        closed: True while the relay is closed (on). Public: signals may read it.
        version: The firmware version byte.
        switches: How many times the relay has changed state.
        command: The last command byte written (None before the first).
    """

    CMD_OFF = 0x00
    CMD_ON = 0x01
    CMD_FIRMWARE_VERSION = 0x04
    CMD_STATUS = 0x05

    def __init__(self, version=0x01):
        self.closed = False
        self.version = version
        self.switches = 0
        self.command = None

    def _reply(self, cmd):
        if cmd == self.CMD_STATUS:
            return int(self.closed)
        if cmd == self.CMD_FIRMWARE_VERSION:
            return self.version
        raise OSError(5, "EIO: no reply for command {}".format(cmd))

    def raw_write(self, data):
        self.command = data[0]
        if data[0] in (self.CMD_OFF, self.CMD_ON):
            closed = data[0] == self.CMD_ON
            if closed != self.closed:
                self.switches += 1
            self.closed = closed

    def raw_read(self, nbytes):
        return bytes([self._reply(self.command)]) * nbytes

    def mem_read(self, reg, nbytes):
        self.command = reg
        return bytes([self._reply(reg)]) * nbytes

