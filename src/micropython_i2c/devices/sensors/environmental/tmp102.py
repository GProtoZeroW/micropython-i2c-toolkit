"""TI TMP102 digital temperature sensor (SBOS397I).

Usage on the board::

    from micropython_i2c import I2CConnection
    from micropython_i2c.devices.sensors.environmental.tmp102 import TMP102

    tmp = TMP102(I2CConnection(bus, 0x48, lock=bus_lock))
    print(tmp.temperature())        # -> 23.4375

Two classes:

* ``TMP102Regs``: datasheet facts only (addresses, registers, fields, code tables,
  masks), no methods. Bring-up uses it to exercise ``RegisterI2CBase`` directly against
  the part, so a failure there cannot be driver logic.
* ``TMP102``: the driver, adding interpretation on top.

Data format, the part that bites: temperature, T_HIGH and T_LOW are *left-justified*
two's complement, 12 bits (normal) or 13 bits (extended mode, EM=1), 0.0625 C/LSB. Shift
the padding out **before** sign extension. Datasheet Tables 6-2/6-3 print the
right-justified count in their HEX column (50 C as ``320``); the wire word is in Tables
6-8/6-9 (``0x3200``).

Generated by ``device_notebooks/sensors/environmental/tmp102_devNB``: edit the notebook, not
this file.
"""

