def crc8_07(data, crc=0xFF):
    """CRC-8, polynomial 0x07, seeded 0xFF (the TMAG5273's)."""
    for byte in data:
        crc ^= byte
        for _ in range(8):
            crc = ((crc << 1) ^ 0x07) & 0xFF if crc & 0x80 else (crc << 1) & 0xFF
    return crc

