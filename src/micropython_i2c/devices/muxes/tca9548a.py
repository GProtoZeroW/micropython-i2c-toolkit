"""TI TCA9548A 8-channel I2C multiplexer (the SparkFun Qwiic Mux).

Usage on the board::

    from micropython_i2c.devices.muxes.tca9548a import TCA9548A

    mux = TCA9548A(bus, 0x70, lock=bus_lock)
    mux.channel_select(2)            # only channel 2 connected
    mux.channels_get()               # -> [2]
    mux.channel_scan()               # -> {0: [0x70], 1: [], 2: [0x48], ...}
    mux.channel_deselect()           # everything downstream isolated

One 8-bit control register with no register pointer: each bit enables one channel, so
writing ``1 << ch`` selects exactly that channel and ``0x00`` isolates everything. Power-on
value is ``0x00``. The address is ``0x70`` plus the A2..A0 straps (``0x70``..``0x77``); on
the SparkFun board those are solder jumpers, open by default (``0x70``).

Generated by ``device_notebooks/muxes/tca9548a_devNB``: edit the notebook, not this file.
"""

