class TCA9548A(I2CMux):
    """TCA9548A driver implementing the ``I2CMux`` channel API."""

    ALLOWED_ADDRS = tuple(range(0x70, 0x78))  # 0x70 + A2..A0 straps
    ADDR_DEFAULT = 0x70  # SparkFun Qwiic Mux with every address jumper open
    CHANNELS = 8
    BAUD_NOMINAL = 400_000
    BAUD_MAX = 400_000
    BAUD_MIN = 10_000
    CONTROL_POR = 0x00  # every channel off after power-on or reset

    def channel_select(self, channel):
        """Enable only ``channel``.

        Raises:
            ValueError: If ``channel`` is not 0..7.
        """
        self.channel_check(channel)
        self.write_raw(bytes([1 << channel]))

    def channel_mask_set(self, mask):
        """Enable every channel whose bit is set in ``mask`` (several at once)."""
        self.write_raw(bytes([mask & 0xFF]))

    def channel_deselect(self):
        """Disable every channel."""
        self.write_raw(b"\x00")

    def control_read(self):
        """The control register: one bit per enabled channel."""
        return self.read_raw(1)[0]

    def channels_get(self):
        """The enabled channels, lowest first, decoded from the control register."""
        mask = self.control_read()
        return [ch for ch in range(self.CHANNELS) if mask & (1 << ch)]

    def channel_scan(self, channels=None):
        """Scan behind each channel; return ``{channel: [addresses]}``.

        Each list holds the addresses that answer with that channel on and did **not** answer
        with every channel off, so the mux itself and anything upstream are left out. A part
        at the mux's own address is therefore invisible (the address clash). Holds the bus
        lock for the whole sequence and always ends with every channel off.

        Args:
            channels: The channels to scan; default all.

        Raises:
            ValueError: If a channel is not 0..7 (before any bus traffic).
        """
        chans = list(range(self.CHANNELS)) if channels is None else list(channels)
        for ch in chans:
            self.channel_check(ch)
        bus, path, found = self.conn.bus, self.conn.path, {}
        with self.conn.lock:
            path_select(bus, path)
            try:
                bus.writeto(self.addr, b"\x00")
                root = set(bus.scan())
                for ch in chans:
                    bus.writeto(self.addr, bytes([1 << ch]))
                    found[ch] = sorted(set(bus.scan()) - root)
            finally:
                bus.writeto(self.addr, b"\x00")
                path_release(bus, path)
        return found

