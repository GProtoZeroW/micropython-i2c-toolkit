"""Signals: physical quantities that change over (simulated) time, for the fakes.

A signal is any callable ``f(t_s)`` returning a value at time ``t_s`` seconds. A fake's quantity
is a plain value or a signal; the fake reads it with ``value(x)``, which calls a signal at the
current ``compat`` time (``SimClock`` time inside a ``with SimClock()`` block) and returns a
plain value unchanged. Tuples and lists are resolved item by item, so a 3-axis field can be
``(ramp(...), 0.0, sine(...))``.

The builders here cover the common shapes; any ``lambda t: ...`` works too, including one that
reads another fake (``lambda t: 30.0 if relay.closed else 20.0``).

Host only: uses CPython's ``math`` and ``random``.

Generated by ``dev_notebooks/sim_signals_devNB``: edit the notebook, not this file.
"""

