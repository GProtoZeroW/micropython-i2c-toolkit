"""``SimClock``: simulated time for drivers and fakes on the host.

Install it with ``with SimClock() as clock:``. Inside the block every ``compat`` timing call
(``sleep_ms``, ``sleep_us``, ``ticks_ms``, ``ticks_us``) uses simulated time: a sleep returns at
once and moves the clock forward by exactly the time asked for. Time moves only then, or when
the test calls ``advance``. A one-hour scenario runs in milliseconds and the same way every
time.

Host only: ``compat.clock_set`` refuses on MicroPython.

Generated by ``dev_notebooks/sim_clock_devNB``: edit the notebook, not this file.
"""

