"""``FakeBus``, a ``machine.I2C`` stand-in with mux routing, and generic fake parts.

``FakeBus`` models mux routing: a part attached behind ``[(mux_addr, ch), ...]`` answers only
while every mux on that path has the channel enabled, the way real silicon does. A part is any
object with some of ``raw_write(data)``, ``raw_read(n)``, ``mem_write(reg, data)``,
``mem_read(reg, n)``, and optionally ``hear(byte)`` (sees every address byte on the bus) and
``bus_addr`` (the address it answers at, if it can change). A part refuses a transfer the way a
real one NACKs: by raising ``OSError``.

Generic parts: ``FakeRegisterPart`` (an 8-bit register file), ``FakeMux`` (one control byte, one
bit per channel) and ``FakeSensirion`` (canned 16-bit words, each followed by a CRC). Each real
part's fake sits next to its driver as ``<part>_fake.py``.

Host only.

Generated by ``dev_notebooks/sim_bus_devNB``: edit the notebook, not this file.
"""

