class FakeSensirion:
    """A command part returning canned words, each followed by ``crc_fn(word bytes)``.

    Args:
        words: The 16-bit words every read returns, in order.
        crc_fn: ``crc_fn(two bytes) -> int``, the checksum sent after each word.

    Attributes:
        commands: Every command written, as an int.
    """

    def __init__(self, words, crc_fn):
        self.words = words
        self.crc_fn = crc_fn
        self.commands = []

    def raw_write(self, data):
        self.commands.append(int.from_bytes(data, "big"))

    def raw_read(self, nbytes):
        out = b""
        for w in self.words:
            pair = w.to_bytes(2, "big")
            out += pair + bytes([self.crc_fn(pair)])
        return out[:nbytes]

