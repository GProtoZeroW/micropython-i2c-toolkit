"""``SimBench``: a whole I2C bench on the host, from the same routing config as the real one.

``SimBench(config, parts)`` makes a ``FakeBus`` per bus, attaches each mux's and device's fake
(``devices.fake_class``) at its address and path, and builds the muxes and drivers through the
real ``I2CManager``. Run it inside ``with SimClock():`` to use simulated time::

    with SimClock() as clock:
        bench = SimBench(CONFIG, parts={"temp": {"temp_c": ramp(20.0, 26.0, 0, 3600)}})
        bench.build()
        clock.advance(1800)
        bench["temp"].temperature()      # about 23 C, half way up the ramp

``parts[name]`` is a dict of keyword arguments for that part's fake, or a ready-made fake
object (for a part with no registered fake, or one the test built itself).

Host only.

Generated by ``dev_notebooks/sim_bench_devNB``: edit the notebook, not this file.
"""

