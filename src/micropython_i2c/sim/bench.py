class SimBench:
    """A fake bench built from a routing config.

    Args:
        config: The routing config (JSON text or dict), as for ``RoutingTable.loads``.
        parts: ``{name: kwargs dict or fake object}`` for muxes and devices; a name left out
            gets its fake with default arguments.
        board: A board name or dict for the bus clocks; default 400 kHz on every bus.

    Attributes:
        table: The validated ``RoutingTable``.
        buses: ``{bus_id: FakeBus}``.
        fakes: ``{name: fake part}`` for every mux and device.
        manager: The ``I2CManager``; ``build()`` builds its muxes and drivers.

    Raises:
        ConfigError: If the config is invalid.
        KeyError: If a driver has no registered fake and ``parts`` gives none.
    """

    def __init__(self, config, parts=None, board=None):
        table = RoutingTable.loads(config)
        names = {e["driver"] for _, e in table.entries() if e.get("driver")}
        reg = registry(sorted(names))
        self.table = table.validate(reg)
        self.buses = {bus_id: FakeBus() for bus_id in table.buses}
        self.fakes = {}
        parts = parts or {}
        for name, entry in table.entries():
            part = self._fake_for(name, entry, parts.get(name))
            path = table.resolve_path(entry["path"])
            self.buses[entry["bus"]].attach(entry["address"], part, path)
            self.fakes[name] = part
        if board is None:
            cap = {"scl": None, "sda": None, "baud_max": 400_000}
            board = {"buses": {b: dict(cap) for b in table.buses}}
        self.manager = I2CManager(self.table, reg, board, bus_factory=self._bus)

    @staticmethod
    def _fake_for(name, entry, given):
        if given is not None and not isinstance(given, dict):
            return given  # a ready-made fake
        kwargs = dict(given or {})
        cls = fake_class(entry["driver"])
        if getattr(cls, "TAKES_ADDR", False):
            kwargs.setdefault("addr", entry["address"])
        return cls(**kwargs)

    def _bus(self, bus_id, cfg, freq):
        return self.buses[bus_id]

    def build(self):
        """Build the buses, muxes and drivers (each driver checks its part's identity)."""
        self.manager.build()
        return self

    def scan(self, verbose=True):
        """``scan_check`` on the fake buses: does every part answer where the config says."""
        if not self.manager.buses:
            self.manager.buses_build()
        return self.manager.scan(verbose)

    def fake(self, name):
        """The fake part behind config name ``name``."""
        return self.fakes[name]

    def __getitem__(self, name):
        """The driver (or mux) named ``name``. Call ``build()`` first."""
        return self.manager[name]

