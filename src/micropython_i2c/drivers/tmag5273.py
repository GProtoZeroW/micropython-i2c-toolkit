def _streamed(name):
    """The axes a fast read sends for a ``MAG_CH_EN`` name: each once, in name order."""
    out = ()
    for axis in name:
        if axis not in out:
            out += (axis,)
    return out


_CH_SEQUENCE = {code: _streamed(name) for code, name in _MAG_CH.items()}

