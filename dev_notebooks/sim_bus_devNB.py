# %% [markdown]
# ## `FakeRegisterPart`
# An 8-bit register file. A read or write starting at `reg` continues at `reg + 1` (auto-
# increment, wrapping at `size`). `read_only` maps a register to the mask of bits that keep their
# value on a write. A bare `raw_read` reads from register 0; `raw_write` is ignored.

# %%
# %%extract ../src/micropython_i2c/sim/bus.py -a
class FakeRegisterPart:
    """A register-mapped part with an auto-incrementing 8-bit register file.

    Args:
        regs: ``{register: value}`` to start with; everything else is 0.
        read_only: ``{register: mask}``: bits set in ``mask`` keep their value on a write.
        size: Number of registers.

    Attributes:
        regs: The register file (``bytearray``).
    """

    def __init__(self, regs=None, read_only=None, size=256):
        self.regs = bytearray(size)
        for reg, val in (regs or {}).items():
            self.regs[reg] = val
        self.read_only = read_only or {}

    def mem_read(self, reg, nbytes):
        return bytes(self.regs[(reg + i) % len(self.regs)] for i in range(nbytes))

    def mem_write(self, reg, data):
        for i, b in enumerate(data):
            r = (reg + i) % len(self.regs)
            keep = self.read_only.get(r, 0)
            self.regs[r] = (self.regs[r] & keep) | (b & ~keep & 0xFF)

    def raw_read(self, nbytes):
        return self.mem_read(0, nbytes)

    def raw_write(self, data):
        pass


# %% [markdown]
# ## `FakeMux`
# One control byte: bit `n` enables channel `n`, and a write replaces the whole byte (the
# TCA9548A scheme). A read returns the byte. The TCA9548A's own fake, with its address range and
# reset, builds on this in `muxes/tca9548a_devNB`.

# %%
# %%extract ../src/micropython_i2c/sim/bus.py -a
class FakeMux:
    """A mux with one control byte, one bit per channel.

    Attributes:
        state: The control byte: bit ``n`` set means channel ``n`` is connected.
    """

    def __init__(self):
        self.state = 0

    def raw_write(self, data):
        self.state = data[-1]

    def raw_read(self, nbytes):
        return bytes([self.state] * nbytes)


# %% [markdown]
# ## `FakeSensirion`
# A command part that answers every read with the same canned 16-bit words, each followed by
# `crc_fn` of its two bytes (Sensirion parts send a CRC-8 after every word). Every command
# written is logged in `commands`, so a test can check what the driver sent.

# %%
# %%extract ../src/micropython_i2c/sim/bus.py -a
class FakeSensirion:
    """A command part returning canned words, each followed by ``crc_fn(word bytes)``.

    Args:
        words: The 16-bit words every read returns, in order.
        crc_fn: ``crc_fn(two bytes) -> int``, the checksum sent after each word.

    Attributes:
        commands: Every command written, as an int.
    """

    def __init__(self, words, crc_fn):
        self.words = words
        self.crc_fn = crc_fn
        self.commands = []

    def raw_write(self, data):
        self.commands.append(int.from_bytes(data, "big"))

    def raw_read(self, nbytes):
        out = b""
        for w in self.words:
            pair = w.to_bytes(2, "big")
            out += pair + bytes([self.crc_fn(pair)])
        return out[:nbytes]


# %% [markdown]
# ## `FakeBus`
# The bus. `attach(addr, part, path)` puts a part at `addr` behind `path`
# (`[(mux_addr, channel), ...]`, outermost first; empty for the root segment). A part is visible
# when every mux on its path is itself visible and has that channel on. A part with a
# `bus_addr` attribute answers there instead of at the address it was attached at (the VL53L1X
# and TMAG5273 can change their address).
#
# A part with a `hear(byte)` method gets every address byte on its segment before the transfer
# (the TMAG5273's CRC covers address bytes it overheard). Visibility is checked before the
# transfer: a mux switches only after its own address byte.

# %%
# %%extract ../src/micropython_i2c/sim/bus.py -a
class FakeBus:
    """Stands in for ``machine.I2C``. Attach parts with ``attach(addr, part, path)``.

    Attributes:
        nodes: ``[(path tuple, addr, part), ...]`` in attach order.
        log: Every transfer: ``("w", addr, data)``, ``("r", addr, n)``,
            ``("wm", addr, reg, data)``, ``("rm", addr, reg, n)``.
    """

    def __init__(self):
        self.nodes = []
        self.log = []

    def attach(self, addr, part, path=()):
        """Put ``part`` at ``addr`` behind ``path``; returns ``part``."""
        self.nodes.append((tuple(tuple(h) for h in path), addr, part))
        return part

    def _mux_at(self, path, addr):
        for p, a, part in self.nodes:
            if p == path and a == addr:
                return part
        raise LookupError("no mux at {:#04x} on {}".format(addr, path))

    def _visible(self, path):
        for i, (maddr, ch) in enumerate(path):
            if not self._visible(path[:i]):
                return False
            if not self._mux_at(path[:i], maddr).state & (1 << ch):
                return False
        return True

    @staticmethod
    def _addr_of(addr, part):
        """The address a part answers at: its ``bus_addr`` if it has one, else ``addr``."""
        return getattr(part, "bus_addr", addr)

    def _targets(self, addr):
        hits = [
            part for p, a, part in self.nodes if self._addr_of(a, part) == addr and self._visible(p)
        ]
        if not hits:
            raise OSError(19, "ENODEV")
        return hits

    def _target(self, addr):
        """The one part a read talks to. Two parts at one address answering a read is a
        collision (their data would be mixed); a write simply reaches both."""
        hits = self._targets(addr)
        if len(hits) > 1:
            raise RuntimeError("bus collision at {:#04x}".format(addr))
        return hits[0]

    def scan(self):
        return sorted({self._addr_of(a, part) for p, a, part in self.nodes if self._visible(p)})

    def _hear(self, addr, read):
        """Give the address byte to every visible part that has a ``hear`` hook."""
        byte = (addr << 1) | (1 if read else 0)
        for path, _, part in self.nodes:
            if hasattr(part, "hear") and self._visible(path):
                part.hear(byte)

    def writeto(self, addr, data, stop=True):
        self.log.append(("w", addr, bytes(data)))
        self._hear(addr, False)
        for part in self._targets(addr):  # every part at the address receives a write
            part.raw_write(bytes(data))
        return len(data)

    def readfrom(self, addr, nbytes, stop=True):
        self.log.append(("r", addr, nbytes))
        self._hear(addr, True)
        return self._target(addr).raw_read(nbytes)

    def readfrom_into(self, addr, buf, stop=True):
        buf[:] = self.readfrom(addr, len(buf))

    def writeto_mem(self, addr, reg, data, addrsize=8):
        self.log.append(("wm", addr, reg, bytes(data)))
        self._hear(addr, False)
        self._target(addr).mem_write(reg, bytes(data))

    def readfrom_mem(self, addr, reg, nbytes, addrsize=8):
        self.log.append(("rm", addr, reg, nbytes))
        self._hear(addr, False)
        self._hear(addr, True)  # the repeated start
        return self._target(addr).mem_read(reg, nbytes)

    def readfrom_mem_into(self, addr, reg, buf, addrsize=8):
        buf[:] = self.readfrom_mem(addr, reg, len(buf), addrsize)


