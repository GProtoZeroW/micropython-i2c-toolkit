# %% [markdown]
# # Intent
# **Purpose:** let the drivers, the connection layer and the manager run on the host exactly as
# on the board, with fake parts at the other end of the wire.
#
# **Why it exists:** a driver only ever calls the `machine.I2C` methods (`writeto`, `readfrom`,
# `readfrom_mem`, ...). `FakeBus` has the same methods and hands each transfer to whichever fake
# part answers at that address, so a driver cannot tell it is not on the board. Mux routing is
# the part that makes this worth having: a mistake in path selection shows up as `ENODEV`, the
# same as on the bench.
#
# ```mermaid
# flowchart LR
#     D[driver] --> C[I2CConnection] --> B[FakeBus]
#     B -->|0x70 always visible| M[FakeMux]
#     B -->|0x48 only while mux ch 2 on| T[FakeTMP102]
#     B -->|0x18| R[FakeRelay]
# ```
#
# | Event | What `FakeBus` does |
# |---|---|
# | write to an address | every visible part there gets it (a write cannot collide) |
# | read from an address | the one visible part there answers; two is a `RuntimeError` (a collision) |
# | nothing visible at the address | `OSError(19, "ENODEV")`, as `machine.I2C` raises for a NACK |
# | any transfer | every visible part with `hear` sees the address byte first |
#
# **Not its job:** electrical faults (pull-ups, clock speed, a stuck line) and timing on the wire.
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `FakeBus` | the `machine.I2C` stand-in; `attach(addr, part, path)`; `log` of every transfer |
# | `FakeRegisterPart` | 8-bit register file with auto-increment and read-only bits |
# | `FakeMux` | one control byte, one bit per channel (the TCA9548A scheme) |
# | `FakeSensirion` | a command part returning canned words, each followed by a CRC |

