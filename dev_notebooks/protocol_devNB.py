# A demo register map for the cells below, shaped like a TMP102 so the tests check the same
# things the TMP102-based tests did before (2026-11-16): 16-bit big-endian registers, a
# configuration register whose resolution bits `RES` (bits 14..13) always read back `11`, a
# status bit `OS` (15) and an alert bit `AL` (5) that a write does not set. `FakeRegisterPart`
# is a file of 8-bit registers with auto-increment, so a 16-bit register at `n` occupies bytes
# `n` and `n + 1`: the registers sit at every other address.
#
# | Register | Address | Starts at | Read-only bits |
# |---|---|---|---|
# | `REG_TEMP` | `0x00` | `0x1900` (25 C in TMP102 counts) | none |
# | `REG_CONFIG` | `0x02` | `0x60A0` | `OS`, `RES`, `AL` |
# | `REG_THIGH` | `0x04` | `0x5000` | none |

# %%
# %%extract ../tests/test_protocol.py -a
class DemoRegs(RegisterI2CBase, I2CDevice):
    """A TMP102-shaped register map on a generic register part."""

    ALLOWED_ADDRS = (0x48,)
    REG_TEMP = 0x00
    REG_CONFIG = 0x02
    REG_THIGH = 0x04
    F_OS = (15, 1)  # status: reads 0 here, ignored by the verify mask
    F_RES = (13, 2)  # read-only, always 0b11
    F_SD = (8, 1)
    F_CR = (6, 2)
    F_AL = (5, 1)  # read-only
    CONV_RATES = {0: 0.25, 1: 1.0, 2: 4.0, 3: 8.0}
    CFG_POR = 0x60A0
    CONFIG_VERIFY_MASK = 0xFFFF & ~((1 << 15) | (3 << 13) | (1 << 5))
    VERIFY_MASKS = {REG_CONFIG: CONFIG_VERIFY_MASK}


def demo_part():
    """The register file behind ``DemoRegs``: TEMP 0x1900, CONFIG 0x60A0, THIGH 0x5000."""
    regs = {0x00: 0x19, 0x01: 0x00, 0x02: 0x60, 0x03: 0xA0, 0x04: 0x50, 0x05: 0x00}
    return FakeRegisterPart(regs, read_only={0x02: 0xE0, 0x03: 0x20})


