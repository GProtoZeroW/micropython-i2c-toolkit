class WordsBus:
    """Answers reads with ``words``, each followed by ``crc_fn(pair)``; logs every transfer."""

    def __init__(self, words, crc_fn):
        self.words = words
        self.crc_fn = crc_fn
        self.log = []

    def writeto(self, addr, data, *args):
        self.log.append(("w", addr, bytes(data)))
        return len(data)

    def readfrom(self, addr, nbytes, *args):
        self.log.append(("r", addr, nbytes))
        out = b""
        for w in self.words:
            pair = bytes([w >> 8, w & 0xFF])
            out += pair + bytes([self.crc_fn(pair)])
        return out[:nbytes]


