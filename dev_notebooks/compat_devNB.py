# %% [markdown]
# ## The timing functions
# On MicroPython these are the `time` module's own functions, bound once at import. On CPython
# each one calls the current clock, so swapping the clock changes every caller at once, even
# modules that imported `sleep_us` by name before the swap.
#
# `ticks_add` and `ticks_diff` wrap on MicroPython (the counters roll over); on CPython they are
# plain arithmetic, because the counters never wrap there.

# %%
# %%extract ../src/micropython_i2c/compat.py -a
try:
    sleep_ms = time.sleep_ms
    sleep_us = time.sleep_us
    ticks_ms = time.ticks_ms
    ticks_us = time.ticks_us
    ticks_add = time.ticks_add
    ticks_diff = time.ticks_diff
    _MICROPYTHON = True
except AttributeError:  # CPython
    _MICROPYTHON = False
    _clock = RealClock()

    def sleep_ms(ms):
        """Sleep ``ms`` milliseconds on the current clock."""
        _clock.sleep_us(int(ms * 1000))

    def sleep_us(us):
        """Sleep ``us`` microseconds on the current clock."""
        _clock.sleep_us(int(us))

    def ticks_ms():
        """Milliseconds on the current clock (does not wrap on CPython)."""
        return _clock.ticks_us() // 1000

    def ticks_us():
        """Microseconds on the current clock (does not wrap on CPython)."""
        return _clock.ticks_us()

    def ticks_add(ticks, delta):
        """Offset a tick value; plain addition since CPython ticks never wrap."""
        return ticks + delta

    def ticks_diff(a, b):
        """Signed difference ``a - b`` between two tick values."""
        return a - b


# %% [markdown]
# ## `clock_get` / `clock_set`
# Read and swap the CPython clock. `clock_set` returns the previous clock so a caller can put it
# back (`sim.clock.SimClock` does this as a context manager). On MicroPython there is nothing to
# swap: the timing functions are the hardware's.

# %%
# %%extract ../src/micropython_i2c/compat.py -a
def clock_get():
    """The clock the timing functions use (CPython only).

    Raises:
        NotImplementedError: On MicroPython, where the timing functions are ``time``'s own.
    """
    if _MICROPYTHON:
        raise NotImplementedError("the clock is fixed on MicroPython")
    return _clock


def clock_set(clock):
    """Make every timing function use ``clock``; return the previous clock (CPython only).

    Args:
        clock: Any object with ``ticks_us()`` and ``sleep_us(us)``.

    Raises:
        NotImplementedError: On MicroPython.
        TypeError: If ``clock`` lacks ``ticks_us`` or ``sleep_us``.
    """
    global _clock
    if _MICROPYTHON:
        raise NotImplementedError("the clock is fixed on MicroPython")
    for name in ("ticks_us", "sleep_us"):
        if not callable(getattr(clock, name, None)):
            raise TypeError("clock {!r} has no {}() method".format(clock, name))
    previous, _clock = _clock, clock
    return previous


