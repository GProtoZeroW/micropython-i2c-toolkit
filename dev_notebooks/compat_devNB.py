# %% [markdown]
# # Intent
# **Purpose:** one place for the things MicroPython and CPython do differently: millisecond and
# microsecond sleeps, the wrapping `ticks` counters, and locks.
#
# **Why it exists:** the package runs on the board and imports on the host. Without this module
# every driver would need `try: time.sleep_ms ... except AttributeError` of its own, and host
# tests would need monkeypatching.
#
# **The clock.** On CPython every timing call goes through one clock object:
#
# ```mermaid
# flowchart LR
#     D[driver / fake] -->|sleep_us, ticks_ms| C[compat]
#     C -->|MicroPython| T[time module]
#     C -->|CPython| K{clock}
#     K --> R[RealClock: wall clock]
#     K --> S[SimClock: simulated time]
# ```
#
# `clock_set(clock)` swaps it and returns the previous one. A clock needs two methods:
# `ticks_us()` (microseconds since the clock started) and `sleep_us(us)`.
#
# **Used by:** every driver (waits), the fakes (measurement timing), `sim.clock`.
#
# **Not its job:** wrapping arithmetic on CPython. CPython ticks never wrap, so `ticks_add` and
# `ticks_diff` are plain `+` and `-` there.
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `sleep_ms`, `sleep_us` | sleep, through the clock on CPython |
# | `ticks_ms`, `ticks_us` | monotonic counters, through the clock on CPython |
# | `ticks_add`, `ticks_diff` | tick arithmetic (wrapping on MicroPython) |
# | `RealClock` | the CPython wall clock, the default |
# | `clock_get`, `clock_set` | read and swap the CPython clock |
# | `NullLock` | a lock that does nothing, for builds without `_thread` |
# | `default_lock` | a real lock where there is one, else a `NullLock` |

