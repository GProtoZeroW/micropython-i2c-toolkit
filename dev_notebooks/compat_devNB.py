class StepClock:
    """Simulated time for the tests: moves only on sleep."""

    def __init__(self):
        self.now = 0

    def ticks_us(self):
        return self.now

    def sleep_us(self, us):
        self.now += max(0, int(us))


# %% [markdown]
# #### validation: nominal usage
# Swap in the step clock: a 10-second sleep returns at once and the counters move by exactly 10
# seconds. Then put the real clock back.

# %%
import time as _t

sc = StepClock()
before = clock_set(sc)
try:
    wall = _t.monotonic()
    sleep_ms(10_000)
    print("ticks_ms:", ticks_ms(), "| ticks_us:", ticks_us(), "| wall time spent: {:.3f} s".format(_t.monotonic() - wall))
finally:
    clock_set(before)
print("restored the previous clock:", clock_get() is before)

