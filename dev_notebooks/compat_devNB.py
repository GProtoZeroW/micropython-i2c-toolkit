# %% [markdown]
# ## `NullLock`
# A lock that does nothing, for MicroPython builds without `_thread`. It implements just what
# the call sites use (`acquire`, `release`, `with`), so they need no conditional logic. It is
# correct whenever there is no concurrency to guard against.

# %%
# %%extract ../src/micropython_i2c/compat.py -a
try:
    import _thread
except ImportError:  # MicroPython build without threading
    _thread = None


class NullLock:
    """No-op stand-in for a mutex on single-threaded builds."""

    def acquire(self, *args):
        return True

    def release(self):
        pass

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        return False


# %% [markdown]
# ## `default_lock`
# The lock a bus gets: a real `_thread` lock where the build has threads, else a `NullLock`.
# Every connection and mux on one bus shares one lock, so callers normally get it from the
# manager.

# %%
# %%extract ../src/micropython_i2c/compat.py -a
def default_lock():
    """Return a real ``_thread`` lock where available, else a ``NullLock``."""
    return _thread.allocate_lock() if _thread is not None else NullLock()


