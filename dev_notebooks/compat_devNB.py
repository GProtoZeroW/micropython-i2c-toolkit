# %% [markdown]
# ## `RealClock`
# The CPython wall clock. `ticks_us` counts from when the clock was made, so simulated and real
# time both start near zero and a signal written as "ramp from t = 0 s to t = 60 s" means the
# same on either. MicroPython never uses it, but the class exists there too so imports match.

# %%
# %%extract ../src/micropython_i2c/compat.py -a
class RealClock:
    """Wall-clock time for CPython: ``time.monotonic`` and ``time.sleep``.

    Attributes:
        t0: ``time.monotonic()`` when the clock was made; ``ticks_us`` counts from it.
    """

    def __init__(self):
        self.t0 = time.monotonic() if hasattr(time, "monotonic") else 0

    def ticks_us(self):
        """Microseconds since the clock was made."""
        return int((time.monotonic() - self.t0) * 1_000_000)

    def sleep_us(self, us):
        """Sleep ``us`` microseconds of real time."""
        if us > 0:
            time.sleep(us / 1_000_000)


