# ### validation/test
# A stub register device for `show_reg`, shared with the test file: it answers `reg_read`
# from a dictionary and records each call, so a test can see which register and width were
# asked for. No bus is involved.

# %%
# %%extract ../tests/test_debug.py -a
class StubRegisterDevice:
    """Just enough of a register driver for ``show_reg``: ``REG_BYTES`` and ``reg_read``."""

    REG_BYTES = 2

    def __init__(self, regs):
        self.regs = regs
        self.reads = []

    def reg_read(self, reg, nbytes):
        self.reads.append((reg, nbytes))
        return self.regs[reg]


