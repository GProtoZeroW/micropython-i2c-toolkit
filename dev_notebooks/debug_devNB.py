# %% [markdown]
# Notebook-only: the sandbox and the stub device. `sandbox(fn)` runs `fn` with a fresh tally
# and `print` captured inside `micropython_i2c.debug`, and returns `(fn's result, the captured
# text, the tally fn left)`. It restores the section's tally and `print` even if `fn` raises.
#
# **What to do:** nothing.

# %%
captured = []


def capture(*args, sep=" ", end="\n"):
    captured.append(sep.join([str(a) for a in args]) + end)


def sandbox(fn):
    saved = check_counts()
    check_reset()
    del captured[:]
    dbg.print = capture  # module globals come before builtins
    try:
        result = fn()
        counts = check_counts()
    finally:
        del dbg.print
        dbg._tally[0], dbg._tally[1] = saved
    return result, "".join(captured), counts


class StubRegisterDevice:
    REG_BYTES = 2

    def __init__(self, regs):
        self.regs = regs
        self.reads = []

    def reg_read(self, reg, nbytes):
        self.reads.append((reg, nbytes))
        return self.regs[reg]


