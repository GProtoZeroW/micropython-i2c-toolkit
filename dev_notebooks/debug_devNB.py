# ## Checks and the tally
# `check` prints one line and counts it; everything else in this section builds on it or
# reads the count. The tally is a module-level list rather than a class, so a notebook calls
# plain functions, and the host can read it with one `%eval check_counts()`.

# %% [markdown]
# ### The tally
# `[passed, failed]` since the last `check_reset()`. A list so the functions can change it
# without `global`.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
_tally = [0, 0]  # passed, failed

# %% [markdown]
# ### `check`
# Print a `PASS` or `FAIL` line, count it, and return the result as a `bool`, so a cell can
# also branch on it. `passed` may be any value; its truth is what counts.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
def check(label, passed, detail=""):
    """Print a PASS/FAIL line, add it to the tally, and return ``passed``."""
    passed = bool(passed)
    _tally[0 if passed else 1] += 1
    print("  [{}] {:<36} {}".format("PASS" if passed else "FAIL", label, detail))
    return passed


# %% [markdown]
# ### `check_raises`
# A `check` that a call raises `exc_type`. On a pass it prints the exception's message under
# the line and returns the exception, so a cell can check its attributes. An exception of
# another type is not caught: it is a bug in the check, not a failed check.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
def check_raises(label, exc_type, fn, *args, **kwargs):
    """Check that ``fn(*args, **kwargs)`` raises ``exc_type``. Returns the exception or None."""
    try:
        fn(*args, **kwargs)
    except exc_type as e:
        check(label, True)
        print("         ", e)
        return e
    check(label, False, "it did not raise")
    return None


# %% [markdown]
# ### `info`
# A line that reads like a check but is not counted: a measured value, a skipped step.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
def info(message):
    """Print an informational line (not counted as pass or fail)."""
    print("  [info] " + message)


# %% [markdown]
# ### `check_reset`
# Zero the tally. A hardware section calls it once, right after the reload cell.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
def check_reset():
    """Zero the tally."""
    _tally[0] = _tally[1] = 0


# %% [markdown]
# ### `check_counts`
# The tally as a tuple, without printing: the value the host reads with `%eval`, where printed
# output would get in the way.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
def check_counts():
    """``(passed, failed)`` since the last ``check_reset()``, without printing.

    For reading the tally from the host: ``get_ipython().run_line_magic("eval",
    "check_counts()")`` in a ``%%host`` cell.
    """
    return _tally[0], _tally[1]


# %% [markdown]
# ### `check_summary`
# Print the tally and return it. The last board cell of every hardware section.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
def check_summary():
    """Print and return ``(passed, failed)`` since the last ``check_reset()``."""
    passed, failed = _tally
    print("{} passed, {} failed".format(passed, failed))
    return passed, failed


