# # Intent
# **Purpose:** the small printing helpers a bring-up notebook needs on the board: show a
# register as hex, grouped binary and decimal; and print `PASS`/`FAIL` lines that add up to a
# tally at the end of a section.
#
# **Why it exists:** every hardware section ends the same way: `check_summary()` on the board,
# `check_counts()` read by the host with `%eval`, the board released, and the run failed on the
# host if anything failed. One module keeps the line format and the tally the same in every
# notebook.
#
# ```mermaid
# flowchart LR
#     R[check_reset] --> C[check / check_raises]
#     C -->|PASS/FAIL line, tally +1| C
#     C --> S[check_summary: print the tally]
#     S --> H["%%host: %eval check_counts()"]
#     H --> D[%board disconnect]
#     D --> F[fail the run if failed > 0]
# ```
#
# **The tally** is one module-level list, `[passed, failed]`, shared by every caller since the
# last `check_reset()`. `info` lines are not counted.
#
# **Line formats** (these are what the tests pin down):
#
# | Call | Prints |
# |---|---|
# | `check("x", True)` | `  [PASS] x` padded to 36 characters, a space, the detail |
# | `check_raises(...)` when it raises | the `PASS` line, then 10 spaces and the exception message |
# | `check_raises(...)` when it does not | `  [FAIL] <label> ... it did not raise` |
# | `info("m")` | `  [info] m` |
# | `check_summary()` | `<passed> passed, <failed> failed` |
# | `show(0x60A0, "config")` | `config           0x60a0  01100000 10100000  24736` |
#
# **Not its job:** logging or anything the drivers call. Only notebooks use it.
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `bin_bytes` | an int as space-separated 8-bit groups, MSB first |
# | `show` | print a value as hex, grouped binary and decimal |
# | `show_reg` | read a register (raw) and `show` it |
# | `check` | print a `PASS`/`FAIL` line and count it |
# | `check_raises` | a `check` that a call raises a given exception |
# | `info` | print an uncounted information line |
# | `check_reset` | zero the tally |
# | `check_counts` | the tally, without printing |
# | `check_summary` | print and return the tally |

