def reset_after_checks():
    check("a", True)
    check("b", False)
    check_reset()
    return check_counts()


result, out, counts = sandbox(reset_after_checks)
check("test_check_reset_zeroes_the_tally", result == (0, 0))
result, out, counts = sandbox(check_counts)
check("test_check_counts_prints_nothing", result == (0, 0) and out == "", repr(out))


def summary_of_three():
    check("a", True)
    check("b", True)
    check("c", False)
    del captured[:]  # keep only what check_summary prints
    return check_summary()


result, out, counts = sandbox(summary_of_three)
check("test_check_summary_prints_and_returns_the_tally",
      result == (2, 1) and counts == (2, 1) and out == "2 passed, 1 failed\n", repr(out))  # fmt: skip

# %% [markdown]
# **Matches** `test_bin_bytes_groups_msb_first`, `test_show_line_format`,
# `test_show_pads_a_zero_high_byte` and `test_show_refuses_a_value_that_does_not_fit`:
# MicroPython's `str.format`, including the nested width in `{:#0{}x}`.
#
# **What to do:** nothing.

# %%
check("test_bin_bytes_groups_msb_first",
      bin_bytes(0x60A0) == "01100000 10100000" and bin_bytes(0x15, 1) == "00010101"
      and bin_bytes(0x0102, 3) == "00000000 00000001 00000010")  # fmt: skip
result, out, counts = sandbox(lambda: (show(0x60A0, "config"), show(0x15, "DEVICE_STATUS", 1)))
check("test_show_line_format",
      out == "config           0x60a0  01100000 10100000  24736\n"
             "DEVICE_STATUS    0x15  00010101  21\n", repr(out))  # fmt: skip
result, out, counts = sandbox(lambda: show(0x00A0))
check("test_show_pads_a_zero_high_byte", out.split()[0] == "0x00a0", repr(out))
check_raises("test_show_refuses_a_value_that_does_not_fit: too wide", ValueError, show, 0x1FF, "", 1)
check_raises("test_show_refuses_a_value_that_does_not_fit: negative", ValueError, show, -1)

