# %% [markdown]
# ## Register display
# Three helpers for looking at register values while bringing a part up. The width is always
# explicit (`nbytes`), because a width inferred from the value hides a zero high byte: `0x00A0`
# and `0xA0` are different registers.

# %% [markdown]
# ### `bin_bytes`
# An int as 8-bit binary groups, most significant byte first, so a bitfield can be read off
# against the datasheet's bit numbering.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
def bin_bytes(value, nbytes=2):
    """Format an int as space-separated 8-bit groups, MSB first."""
    return " ".join("{:08b}".format((value >> (8 * i)) & 0xFF) for i in reversed(range(nbytes)))


# %% [markdown]
# ### `show`
# One line per value: label, hex padded to the width, the binary groups, and decimal. A value
# that does not fit the width raises `ValueError` rather than printing a misleading line.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
def show(value, label="", nbytes=2):
    """Print a value as hex, grouped binary and decimal, padded to ``nbytes``.

    The width is explicit because inferring it from magnitude hides a zero high byte.

    Raises:
        ValueError: If ``value`` does not fit in ``nbytes``.
    """
    if not 0 <= value < (1 << (8 * nbytes)):
        raise ValueError("{:#x} does not fit in {} byte(s)".format(value, nbytes))
    print(
        "{:<16} {:#0{}x}  {}  {}".format(
            label, value, nbytes * 2 + 2, bin_bytes(value, nbytes), value
        )
    )


# %% [markdown]
# ### `show_reg`
# Read a register straight from the part (`reg_read`, raw and uncached) and `show` it. The
# width defaults to the driver's `REG_BYTES`, the label to the register address.

# %%
# %%extract ../src/micropython_i2c/debug.py -a
def show_reg(dev, reg, label="", nbytes=None):
    """Read register ``reg`` from ``dev`` (raw, uncached) and ``show`` it."""
    nbytes = dev.REG_BYTES if nbytes is None else nbytes
    show(dev.reg_read(reg, nbytes), label or "reg {:#04x}".format(reg), nbytes)


