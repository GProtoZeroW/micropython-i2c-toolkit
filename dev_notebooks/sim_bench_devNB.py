# %% [markdown]
# ## Example: a whole project in simulated time
# A small greenhouse controller on the bench config above, the kind of program that would run on
# the board. Every minute it reads the soil temperature (TMP102) and drives the heater relay to
# hold 20-22 C, logs the air (SHTC3), watches a door magnet (TMAG5273, Z axis) and looks for a
# visitor (VL53L1X). It uses only the drivers and `compat.sleep_ms`, so the same function runs on
# the board unchanged.
#
# The world it runs in:
#
# | Part | Scenario |
# |---|---|
# | heater relay | a `FakeQwiicRelay` built here, so the soil signal can read its `closed` |
# | soil (TMP102) | `lag` towards 30 C while the heater is on, 12 C while off, time constant 15 min |
# | air (SHTC3) | a 4-hour `sine` around 18 C; humidity 55 %RH with `noisy` spread |
# | door (TMAG5273) | 25 mT on Z while the door is shut; 0.5 mT while open, from minute 60 to 80 |
# | visitor (VL53L1X) | `sequence`: nobody (3 m) until minute 90, walks up to 0.4 m by 95, leaves by 105 |

# %%
# %%extract ../tests/test_sim_bench.py -a
def greenhouse(bench, minutes):
    """The application: one pass a minute. Returns one log row per minute."""
    heater, soil, air, door, tof = (bench[n] for n in ("heater", "soil", "air", "door", "tof"))
    door.configure(channels="XYZ")
    log = []
    for minute in range(minutes):
        t_soil = soil.temperature()
        if t_soil < 20.0:
            heater.on()
        elif t_soil > 22.0:
            heater.off()
        t_air, rh = air.measure()
        door_open = abs(door.magnetic()[2]) < 5.0  # the door magnet holds Z near 25 mT
        visitor = tof.measure().distance_mm < 800
        log.append((minute, t_soil, heater.state, t_air, rh, door_open, visitor))
        sleep_ms(60_000)
    return log


def greenhouse_world():
    """The scenario: the parts dict for SimBench, and the heater's fake."""
    heater = FakeQwiicRelay()
    parts = {
        "heater": heater,
        "soil": {"temp_c": lag(lambda t: 30.0 if heater.closed else 12.0, 900, initial=16.0)},
        "air": {"temp_c": sine(18.0, 3.0, 4 * 3600), "rh": noisy(55.0, 1.0, seed=1)},
        "door": {"field_mT": (0.0, 0.0, lambda t: 0.5 if 3600 <= t < 4800 else 25.0)},
        "tof": {"distance_mm": sequence([(0, 3000), (5400, 3000), (5700, 400), (6000, 400),
                                         (6300, 3000)])},
    }  # fmt: skip
    return parts, heater


# %% [markdown]
# Notebook-only: run the project for three simulated hours, print every 15th minute and a summary,
# and how much real time it took.

# %%
import time

wall = time.monotonic()
with SimClock() as clock:
    parts, heater_part = greenhouse_world()
    bench = SimBench(BENCH, parts=parts).build()
    log = greenhouse(bench, 180)
print("3 simulated hours in {:.2f} s of real time".format(time.monotonic() - wall))
print("min  soil C  heater  air C   %RH   door   visitor")
for minute, t_soil, on, t_air, rh, door_open, visitor in log[::15]:
    print("{:3d}  {:6.2f}  {!s:6}  {:5.2f}  {:5.1f}  {:6} {}".format(
        minute, t_soil, on, t_air, rh, "open" if door_open else "shut", "yes" if visitor else "-"))  # fmt: skip
after_warmup = [row[1] for row in log if row[0] >= 30]
print("soil after warm-up: {:.2f} .. {:.2f} C".format(min(after_warmup), max(after_warmup)))
print("door open minutes:", [r[0] for r in log if r[5]][0], "to", [r[0] for r in log if r[5]][-1])
print("visitor minutes:", [r[0] for r in log if r[6]])

