# **Purpose:** write and test a whole multi-sensor project before (or without) the hardware: the
# same routing config, the same manager, the same drivers, with fake parts whose quantities
# follow scenarios in simulated time.
#
# ```mermaid
# flowchart LR
#     C[routing config] --> T[RoutingTable.validate]
#     T --> B[SimBench]
#     P["parts: values and signals"] --> B
