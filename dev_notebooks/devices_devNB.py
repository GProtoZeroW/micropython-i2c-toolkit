# %% [markdown]
# ## `driver_class`, `registry`, `fake_class`
# `__import__` with a non-empty `fromlist` returns the leaf module on both MicroPython and
# CPython, so one call imports exactly one driver.

# %%
# %%extract ../src/micropython_i2c/devices/__init__.py -a
def _load(table, name):
    module, cls = table[name]
    mod = __import__("micropython_i2c.devices." + module, None, None, [cls])
    return getattr(mod, cls)


def driver_class(name):
    """Import and return the driver class registered as ``name``.

    Raises:
        KeyError: If ``name`` is not in ``DRIVERS``.
    """
    return _load(DRIVERS, name)


def registry(names=None):
    """Return ``{name: class}`` for ``names`` (default: every registered driver)."""
    return {n: driver_class(n) for n in (DRIVERS if names is None else names)}


def fake_class(name):
    """Import and return the fake registered for driver ``name`` (host only).

    Raises:
        KeyError: If ``name`` has no fake in ``FAKES``.
    """
    if name not in FAKES:
        raise KeyError("no fake for driver {!r}: write one in its device notebook".format(name))
    return _load(FAKES, name)


