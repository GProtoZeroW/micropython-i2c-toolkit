# ### validation/test: `sign_extend`
# The TMP102 is the worked example: its temperature register is left-justified, 12 bits in
# normal mode and 13 bits in extended mode (`EM`), with 0.0625 °C per count. The padding bits
# must be shifted out before sign-extending.

# %% [markdown]
# #### validation: nominal usage
# A TMP102 reading of `0xE700` in normal mode: shift out the 4 padding bits, then extend 12
# bits. $-400 \times 0.0625 = -25$ °C.

# %%
word = 0xE700
counts = BitTools.sign_extend(word >> 4, 12)
print("word {:#06x} -> counts {} -> {} C".format(word, counts, counts * 0.0625))
for bits in (8, 12, 16):
    top = 1 << (bits - 1)
    print("{:>2} bits: max {:>6} | min {:>7} | all ones {}".format(
        bits, BitTools.sign_extend(top - 1, bits), BitTools.sign_extend(top, bits),
        BitTools.sign_extend((1 << bits) - 1, bits)))  # fmt: skip

# %% [markdown]
# #### validation: anti-nominal usage
# `sign_extend` raises nothing: it masks. The anti-nominal case is the one the docstring warns
# about, extending the unshifted word, which gives a wrong value silently.

# %%
