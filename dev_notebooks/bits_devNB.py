# %% [markdown]
# # Intent
# **Purpose:** one implementation of the bit and byte arithmetic every driver needs: sign
# extension of an $n$-bit two's-complement reading, `(shift, width)` bitfields in a register
# word, bit reversal, and big- or little-endian byte assembly.
#
# **Why it exists:** these few lines get rewritten in every driver, each time slightly
# differently, and the bugs (sign-extending before shifting out padding, an oversized value
# producing a wrong-length transfer) are the same each time. One class means one place to fix.
#
# **How drivers use it:** through inheritance. `RegisterI2CBase` and `CRCMixin` both subclass
# `BitTools`, so a driver calls `self.sign_extend(...)`, `self.field_insert(...)`. Every method
# is a `staticmethod`, so `BitTools.sign_extend(...)` works unbound too.
#
# ```mermaid
# flowchart BT
#     R[RegisterI2CBase] --> B[BitTools]
#     C[CRCMixin] --> B
#     D[drivers] --> R
#     D --> C
# ```
#
# **Bitfields** are `(shift, width)` tuples declared once as class constants on a driver, e.g.
# the TMP102's conversion-rate field `CR = (6, 2)`: bits 7..6 of the configuration word.
#
# **Not its job:** reading or writing registers (`protocol`), checksums (`crc`).
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `BitTools` | stateless bit and byte helpers, as staticmethods |
# | `BitTools.sign_extend` | read a `bits`-wide value as two's complement |
# | `BitTools.field_mask` | aligned mask of a `(shift, width)` field |
# | `BitTools.field_extract` | a field's value out of a word |
# | `BitTools.field_insert` | a word with one field replaced |
# | `BitTools.bit_reverse` | reverse the bit order of a `bits`-wide value |
# | `BitTools.bytes_to_int` | bytes to an unsigned int, big- or little-endian |
# | `BitTools.int_to_bytes` | an int to `nbytes` bytes, masked to width |

