# %% [markdown]
# ## `scan_check`
# One scan per segment (bus + path), each inside the bus lock: select the path, scan, and release
# it innermost first even if the scan fails, so no mux is left switched on.

# %%
# %%extract ../src/micropython_i2c/manager.py -a
def scan_check(table, buses, locks=None, verbose=True):
    """Confirm every declared address ACKs on its segment.

    Groups entries by segment (bus + path), selects each path, scans once, then releases the
    path innermost first. An ACK means *something* answers at that address, not that it is the
    right part; identity checks confirm the chip.

    Args:
        table: A ``RoutingTable``.
        buses: ``{bus_id: machine.I2C}``.
        locks: Optional ``{bus_id: lock}``; pass the manager's when other code may be using the
            bus concurrently.
        verbose: Print one line per target and a summary.

    Returns:
        ``(all_present, results)`` where each result is a dict with ``bus``, ``hops``, ``addr``,
        ``label`` and ``present``.
    """
    results = []
    for (bus_id, path), members in table.segments().items():
        hops = table.resolve_path(path)
        i2c = buses[bus_id]
        lock = locks[bus_id] if locks else default_lock()
        with lock:
            path_select(i2c, hops)
            try:
                found = set(i2c.scan())
            finally:
                path_release(i2c, hops)
        for addr, label in members:
            results.append(
                {
                    "bus": bus_id,
                    "hops": hops,
                    "addr": addr,
                    "label": label,
                    "present": addr in found,
                }  # fmt: skip
            )

    all_ok = all(r["present"] for r in results)
    if verbose:
        for r in results:
            via = "".join(" via {:#04x}:ch{}".format(a, c) for a, c in r["hops"])
            print(
                "[{}] bus{} {:#04x} {}{}".format(
                    "OK  " if r["present"] else "MISS", r["bus"], r["addr"], r["label"], via
                )
            )
        print("scan_check:", "all present" if all_ok else "MISSING targets")
    return all_ok, results


