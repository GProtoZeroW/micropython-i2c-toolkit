# %% [markdown]
# # Intent
# **Purpose:** turn a validated routing table into live objects: one bus and one lock per bus
# id, a driver instance per mux, then a connection and a driver instance per device.
#
# ```mermaid
# flowchart LR
#     T[RoutingTable] --> M[I2CManager]
#     B[board pin map] --> M
#     R[driver registry] --> M
#     M -->|buses_build| BUS["machine.I2C, or bus_factory(...)"]
#     M -->|muxes_build| MUX[TCA9548A ...]
#     M -->|devices_build| DEV["I2CConnection + driver"]
# ```
#
# **Bus clock:** the lowest `BAUD_MAX` of the board's bus entry and every part on that bus, so a
# 400 kHz part on a 1 MHz board bus runs the bus at 400 kHz. If some part's `BAUD_MIN` is above
# that, the table cannot work and `bus_freq` says so.
#
# **`scan_check`:** before building drivers, check every declared address answers on its
# segment (select the path, scan, release). An answer means *something* is there; the driver's
# identity read confirms what.
#
# **Not its job:** validating the table (`RoutingTable.validate`), or talking to the parts
# beyond building them.
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `scan_check` | check every declared address answers on its segment |
# | `I2CManager` | builds buses (or fakes, via `bus_factory`), muxes and devices; `mgr["name"]` |

