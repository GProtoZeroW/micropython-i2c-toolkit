# # Intent
# **Purpose:** the base classes every part derives from. A node knows two things: the
# datasheet facts about its part (class attributes, readable with no instance) and how to move
# bytes (four transport methods over its `I2CConnection`).
#
# ```mermaid
# classDiagram
#     I2CNode <|-- I2CDevice
#     I2CNode <|-- I2CMux
#     I2CNode : ALLOWED_ADDRS, BAUD_*, REG_ADDR_BITS
#     I2CNode : conn
#     I2CNode : read_mem() write_mem() read_raw() write_raw()
#     I2CMux : CHANNELS
#     I2CMux : channel_select() channel_deselect() control_read() reset()
# ```
#
# **Why four transport methods.** The protocol mixins (`RegisterI2CBase`, `CommandI2CBase`)
# call only these. They never see a bus, an address or a lock, so the same mixin serves a
# sensor three muxes deep and a mux on the bare bus.
#
# **Device vs mux.** A device is handed a connection by the manager. A mux builds its own, from
# the *upstream* path that reaches the mux itself, so a mux never routes through itself.
#
# **Used by:** every driver and mux in `devices`, the manager, the routing table (class
# attributes only).
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `I2CNode` | datasheet facts as class attributes, plus the four-method transport |
# | `I2CDevice` | a routed device, given its connection; the base of ordinary drivers |
# | `I2CMux` | a routing element with its own upstream connection, the mux API and `reset` |

