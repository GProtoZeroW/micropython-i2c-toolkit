def test_the_previous_clock_comes_back_and_blocks_nest():
    before = clock_get()
    outer, inner = SimClock(), SimClock()
    with outer:
        with inner:
            assert clock_get() is inner
        assert clock_get() is outer
    assert clock_get() is before


