# %% [markdown]
# #### validation: nominal usage
# A 10-minute sleep inside the block takes no real time, and both counters move by exactly 10
# minutes. After the block, the wall clock is back.

# %%
wall = time.monotonic()
with SimClock() as clock:
    sleep_ms(600_000)
    sleep_us(250)
    print("simulated: {} s | ticks_ms: {} | sleeps served: {}".format(clock.now_s(), ticks_ms(), clock.sleeps))
print("real time spent: {:.4f} s | wall clock back:".format(time.monotonic() - wall), type(clock_get()).__name__)

# %% [markdown]
# `advance` moves time without a sleep (a test standing in for "the program did something else
# for a minute"), and blocks nest: the inner clock is used inside, the outer one after.

# %%
outer = SimClock(start_s=100)
with outer:
    outer.advance(60)
    with SimClock() as inner:
        sleep_ms(5)
        print("inner:", ticks_ms(), "ms")
    print("outer again:", ticks_ms(), "ms | inner left at:", inner.now_s(), "s")

# %% [markdown]
# #### validation: anti-nominal usage

# %%
c = SimClock()
try:
    c.advance(-1)  # simulated time never goes back
except ValueError as err:
    print("raised ValueError, as expected:\n    {}".format(err))
else:
    raise AssertionError("advance(-1) should have raised ValueError")
finally:
    print("time unchanged:", c.now_us == 0)

# %%
c = SimClock()
try:
    c.uninstall()  # never installed
except RuntimeError as err:
    print("raised RuntimeError, as expected:\n    {}".format(err))
else:
    raise AssertionError("uninstall() of a clock never installed should have raised RuntimeError")
finally:
    print("compat clock untouched:", type(clock_get()).__name__)

