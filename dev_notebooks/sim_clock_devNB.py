# %% [markdown]
# # Intent
# **Purpose:** run drivers and fakes without waiting, and the same way every run.
#
# **Why it exists:** a driver waits real milliseconds (the SHTC3 12.1 ms per measurement, the
# VL53L1X a whole timing budget), and a fake times its measurements on the clock. On the wall
# clock a test of an hour-long scenario would take an hour, and timing races would make it
# flaky. On `SimClock` the driver's `sleep_ms(12)` moves time forward 12 ms at once, and the
# fake sees exactly 12 ms pass.
#
# ```python
# with SimClock() as clock:
#     sht.measure()            # its 12.1 ms wait takes no real time
#     clock.advance(60)        # one simulated minute later
#     clock.now_s()            # 60.0121
# ```
#
# **Not its job:** threads. Simulated time is for single-threaded code; two threads sleeping on
# one simulated clock would each move it forward.
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `SimClock` | simulated time; a context manager that installs itself as the `compat` clock |

