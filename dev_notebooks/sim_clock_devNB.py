def test_sleeps_take_no_real_time_and_add_up_exactly():
    wall = time.monotonic()
    with SimClock() as clock:
        for _ in range(1000):
            sleep_us(1)
        sleep_ms(60_000)
    assert clock.now_us == 60_001_000
    assert time.monotonic() - wall < 1.0


