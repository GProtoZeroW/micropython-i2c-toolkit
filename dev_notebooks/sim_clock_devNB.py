# %% [markdown]
# ## `SimClock`
# Time is a whole number of microseconds, so repeated small sleeps add up exactly (no float
# drift). `install` / `uninstall` swap it in and out of `compat`; the `with` form does both and
# restores whatever clock was there before, so blocks nest.

# %%
# %%extract ../src/micropython_i2c/sim/clock.py -a
class SimClock:
    """Simulated time. Moves only on a sleep or ``advance``.

    Args:
        start_s: Simulated time at creation, in seconds.

    Attributes:
        now_us: Simulated time in microseconds.
        sleeps: How many sleeps the clock has served (handy to check a driver waited).
    """

    def __init__(self, start_s=0):
        self.now_us = int(round(start_s * 1_000_000))
        self.sleeps = 0
        self._previous = []

    # The clock interface compat calls.

    def ticks_us(self):
        """Simulated microseconds."""
        return self.now_us

    def sleep_us(self, us):
        """Move time forward ``us`` microseconds, at once. A negative sleep is a no-op."""
        self.sleeps += 1
        if us > 0:
            self.now_us += int(us)

    # For tests and scenarios.

    def advance(self, seconds):
        """Move time forward ``seconds`` (a float), as if the program had slept that long.

        Raises:
            ValueError: If ``seconds`` is negative: simulated time never goes back.
        """
        if seconds < 0:
            raise ValueError("cannot advance by {} s: time never goes back".format(seconds))
        self.now_us += int(round(seconds * 1_000_000))

    def now_s(self):
        """Simulated time in seconds (a float)."""
        return self.now_us / 1_000_000

    def install(self):
        """Make this the ``compat`` clock. ``uninstall`` puts the previous one back."""
        self._previous.append(clock_set(self))
        return self

    def uninstall(self):
        """Restore the clock that was in place before the matching ``install``.

        Raises:
            RuntimeError: If this clock is not installed.
        """
        if not self._previous:
            raise RuntimeError("this SimClock is not installed")
        clock_set(self._previous.pop())

    def __enter__(self):
        return self.install()

    def __exit__(self, *exc):
        self.uninstall()
        return False


