def crc_class(name="C", params=None, **extra):
    d = dict(params or {})
    d.update(extra)
    return type(name, (CRCMixin,), d)


def run(label, fn):
    try:
        ok = fn()
    except Exception as e:  # report it as a FAIL and go on
        return check(label, False, "raised {}: {}".format(type(e).__name__, e))
    return check(label, ok)


