# %% [markdown]
# # Intent
# **Purpose:** one CRC implementation for every part that checksums its data, configured by
# the part's datasheet facts (width, polynomial, initial value, reflection, final XOR) declared
# as class attributes on the driver.
#
# **Why class attributes:** a part's CRC parameters never change, so they belong with its other
# datasheet facts (`ALLOWED_ADDRS`, register map). A module function `crc8(data, poly, init)`
# would repeat them at every call site, where one would eventually be wrong.
#
# **Why `CRC_POLY` has no default:** a wrong polynomial gives checksums that verify against
# themselves and nothing else, so tests on the host would pass and the real part would fail.
# An unset polynomial raises `NotImplementedError` naming the class.
#
# The model is the usual parameterised ("Rocksoft") CRC:
#
# ```mermaid
# flowchart LR
#     I[CRC_INIT] --> L{for each byte}
#     L -->|CRC_REFLECT_IN: bit_reverse| X[XOR into the top of the accumulator]
#     X --> S[8 shift/XOR steps with CRC_POLY, or one table lookup]
#     S --> L
#     L -->|done| O[CRC_REFLECT_OUT: bit_reverse] --> F[XOR CRC_XOR_OUT] --> R[checksum]
# ```
#
# | Part | `CRC_WIDTH` | `CRC_POLY` | `CRC_INIT` | Covers |
# |---|---|---|---|---|
# | SHTC3 (Sensirion) | 8 | `0x31` ($x^8+x^5+x^4+1$) | `0xFF` | each 16-bit word |
# | TMAG5273 | 8 | `0x07` ($x^8+x^2+x+1$) | `0xFF` | the whole packet, command byte included |
#
# **Used by:** `CommandI2CBase` (Sensirion defaults), the SHTC3 and TMAG5273 drivers.
#
# **Not its job:** deciding which bytes a checksum covers. That is the driver's.
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `CRCMixin` | the CRC model, a `BitTools` subclass configured by `CRC_*` class attributes |
# | `CRCMixin.crc` | the checksum of some bytes, optionally resuming from `init` |
# | `CRCMixin.crc_ok` | `True` if a checksum matches |
# | `CRCMixin.crc_verify` | the checksum, or `ValueError` if it does not match |
# | `CRCMixin.crc_table`, `crc_table_clear` | the lazily built 256-entry lookup table |
# | `CRCMixin.crc_mask`, `crc_topbit` | width-derived constants |
# | `CRCMixin.crc_check_configured` | raise if `CRC_POLY` is unset |

