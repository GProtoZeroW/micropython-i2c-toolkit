def table_lazy_cached_and_clearable():
    tbl = crc_class(CRC_POLY=0x07, CRC_TABLE_ENABLE=True)
    fresh = "_crc_tbl" not in tbl.__dict__
    tbl.crc(b"\x00")
    built = len(tbl.crc_table()) == 256 and tbl.crc_table() is tbl.crc_table()
    tbl.crc_table_clear()
    return fresh and built and "_crc_tbl" not in tbl.__dict__


def subclass_builds_own_table():
    parent = crc_class("Parent", CRC_POLY=0x07, CRC_INIT=0xFF, CRC_TABLE_ENABLE=True)
    child = type("Child", (parent,), {"CRC_POLY": 0x31})
    parent.crc(b"\x00")
    return (child.crc(b"\x00") == 0xAC and parent.crc(b"\xe0") == 0x5D
            and parent.crc_table() is not child.crc_table())  # fmt: skip


run("test_table_lazy_cached_and_clearable", table_lazy_cached_and_clearable)
run("test_subclass_builds_own_table", subclass_builds_own_table)

