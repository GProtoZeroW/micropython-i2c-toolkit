# %% [markdown]
# # Intent
# **Purpose:** drive a TCA9548A: connect exactly one channel (or a chosen set) to the upstream
# bus, isolate them all, read back which are on, and find what sits behind each channel.
#
# **Why it exists:** the routing layer (`I2CConnection`, `RoutingTable`, `I2CManager`) needs a
# mux object that implements the `I2CMux` channel API, and bring-up needs a quick answer to
# "what is behind channel n?".
#
# **Used by:** `I2CManager` builds one per mux in the routing table (`"driver": "TCA9548A"`).
# Connections do **not** call it: they write the one-hot channel byte themselves on every
# transfer (`connection.path_select`), under the same bus lock.
#
# **Not its job:** choosing which channel a device needs (the routing table does that).
#
# ```mermaid
# flowchart LR
#     host["board I2C"] --- mux["TCA9548A @ 0x70..0x77"]
#     mux --- c0["ch 0"] --- d0["SHTC3 @ 0x70"]
#     mux --- c2["ch 2"] --- d2["TMP102 @ 0x48"]
#     mux --- cn["ch 1, 3..7"]
# ```
#
# | Control byte | Meaning |
# |---|---|
# | `0x00` | every channel off (power-on) |
# | `1 << ch` | only channel `ch` |
# | any mask | every channel whose bit is set (their devices share the bus: addresses must differ) |
#
# **Address clash.** When a channel is on, the parts behind it and the mux share one bus. A part
# with the mux's own address (an SHTC3 is always `0x70`, the mux's default) cannot be told apart
# from the mux, so the mux must be strapped elsewhere (`0x71`, A0 jumper closed).
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `TCA9548A` | the driver: `channel_select`, `channel_mask_set`, `channel_deselect`, `control_read`, `channels_get`, `channel_scan` |

