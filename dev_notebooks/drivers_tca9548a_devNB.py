# Notebook-only: what is wired behind each channel, as `{channel: (part, addresses)}`. A part may
# answer at any of its listed addresses (the TMAG5273 board here is at `0x22`; its factory
# default is `0x35`). A part at the mux's own address is a **clash**: it cannot be told apart
# from the mux, so checks on its channel are reported instead of passed or failed.
#
# **What to do:** edit `BENCH` if the wiring changed, then run the cell.

# %%
BENCH = {
    0: ("TMAG5273", (0x22, 0x35)),
    2: ("TMP102", (0x48,)),
}


def clashes(ch):
    """True if a part behind ``ch`` has the mux's own address."""
    return ch in BENCH and MUX_ADDR in BENCH[ch][1]


for ch, (part, addrs) in sorted(BENCH.items()):
    note = "  <- CLASH with the mux" if clashes(ch) else ""
    print("channel {}: {} at {}{}".format(ch, part, [hex(a) for a in addrs], note))

# %% [markdown]
# ## Matching tests
# One cell per unit test above, with the same name, on the real mux.

# %% [markdown]
# **Matches** `test_channel_select_enables_only_that_channel`, for all eight channels.
#
# **What to do:** nothing.

# %%
try:
    for ch in range(8):
        mux.channel_select(ch)
        name = "test_channel_select_enables_only_that_channel[{}]".format(ch)
        if clashes(ch):  # two chips answer the control-register read: the value is garbled
            info("{}: {} at the mux address, read-back not checked".format(name, BENCH[ch][0]))
        else:
            check(name, mux.control_read() == 1 << ch and mux.channels_get() == [ch])
finally:
    mux.channel_deselect()

# %% [markdown]
# **Matches** `test_out_of_range_channel_is_refused`.
#
# **What to do:** nothing.

# %%
for ch in (-1, 8, 99):
    check_raises(
        "test_out_of_range_channel_is_refused[{}]".format(ch), ValueError, mux.channel_select, ch
    )
check("still every channel off", mux.channels_get() == [])

# %% [markdown]
# **Matches** `test_mask_set_and_deselect`.
#
# **What to do:** nothing.

# %%
try:
    mux.channel_mask_set(0b1010_0101)
    check("mask 0b10100101 -> channels 0, 2, 5, 7", mux.channels_get() == [0, 2, 5, 7])
    mux.channel_deselect()
    check("test_mask_set_and_deselect", mux.control_read() == TCA9548A.CONTROL_POR)
finally:
    mux.channel_deselect()

# %% [markdown]
# **Matches** `test_parts_appear_only_on_their_channel`: each part in `BENCH` answers only while
# its channel is on.
#
# **What to do:** nothing.

# %%
try:
    mux.channel_deselect()
    root = bus.scan()
    print("all off:   ", [hex(a) for a in root])
    for ch, (part, addrs) in sorted(BENCH.items()):
        mux.channel_select(ch)
        seen = bus.scan()
        print("channel {}: {}".format(ch, [hex(a) for a in seen]))
        if clashes(ch):
            info("{} on channel {} has the mux address: cannot be told apart".format(part, ch))
        else:
            check("{} only with channel {} on".format(part, ch),
                  any(a in seen and a not in root for a in addrs))  # fmt: skip
finally:
    mux.channel_deselect()

# %% [markdown]
# **Matches** `test_channel_scan_finds_the_bench`: the whole map in one call, and every channel
# off afterwards.
#
# **What to do:** nothing.

# %%
mux.channel_select(5)  # left on before the scan, as in the unit test
scan = mux.channel_scan()
for ch, addrs in sorted(scan.items()):
    print("  channel {}: {}".format(ch, [hex(a) for a in addrs]))
for ch, (part, addrs) in sorted(BENCH.items()):
    if clashes(ch):
        info("{} on channel {}: hidden by the clash (expected)".format(part, ch))
    else:
        check(
            "{} on channel {}".format(part, ch),
            any(a in scan[ch] for a in addrs),
            str([hex(a) for a in scan[ch]]),
        )
unexpected = {ch: a for ch, a in scan.items() if a and ch not in BENCH}
if unexpected:
    info(
        "parts on channels not in BENCH: {}".format(
            {ch: [hex(x) for x in a] for ch, a in unexpected.items()}
        )
    )
check("test_channel_scan_finds_the_bench (all off after)", mux.channels_get() == [])

# %% [markdown]
# **Matches** `test_channel_scan_cannot_see_a_part_at_the_mux_address`. On the real bench this
# only applies when a part in `BENCH` has the mux's address; otherwise it is reported and
# skipped.
#
# **What to do:** nothing.

# %%
clash_chs = [ch for ch in BENCH if clashes(ch)]
if clash_chs:
    hidden = mux.channel_scan(clash_chs)
    check("test_channel_scan_cannot_see_a_part_at_the_mux_address",
          all(MUX_ADDR not in hidden[ch] for ch in clash_chs))  # fmt: skip
else:
    info("no part in BENCH has the mux address {:#04x}: no clash on this bench".format(MUX_ADDR))

# %% [markdown]
# **Matches** `test_channel_scan_refuses_bad_channels_first`.
