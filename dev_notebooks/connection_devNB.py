# %% [markdown]
# **Matches** `test_select_and_transfer_happen_under_the_lock` and
# `test_lock_released_when_transfer_fails`, on the board's own lock. A small wrapper notes, at
# each bus call, whether the lock was held. On a build without `_thread` the lock is a
# `NullLock` and there is nothing to check.
#
# **What to do:** nothing.

# %%
class LockWatchBus:
    """Wraps the bus; ``held`` records, per call, whether ``lock`` was held."""

    def __init__(self, inner, lock):
        self.inner = inner
        self.lock = lock
        self.held = []

    def _note(self):
        free = self.lock.acquire(0)
        if free:
            self.lock.release()
        self.held.append(not free)

    def writeto(self, addr, data, *args):
        self._note()
        return self.inner.writeto(addr, data, *args)

    def readfrom_mem(self, addr, reg, nbytes, addrsize=8):
        self._note()
        return self.inner.readfrom_mem(addr, reg, nbytes, addrsize=addrsize)


if isinstance(bus_lock, NullLock):
    info("no _thread on this build: the lock is a NullLock, nothing to check")
else:
    watch = LockWatchBus(bus, bus_lock)
    I2CConnection(watch, TMP_ADDR, TMP_PATH, bus_lock).readfrom_mem(TMP_REG_CONFIG, 2)
    check("test_select_and_transfer_happen_under_the_lock", watch.held == [True, True])
    path_release(bus, TMP_PATH)
    try:
        I2CConnection(watch, TMP_ADDR, [], bus_lock).readfrom_mem(TMP_REG_CONFIG, 1)
    except OSError:
        pass
    free = bus_lock.acquire(0)
    if free:
        bus_lock.release()
    check("test_lock_released_when_transfer_fails", free)

