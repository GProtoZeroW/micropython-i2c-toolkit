# %% [markdown]
# # Intent
# **Purpose:** one object per physical device that carries everything needed to reach it: the
# bus, the mux hops in front of it, its address and the bus lock. A driver holding a connection
# calls `readfrom_mem(reg, n)` and never names an address or a mux.
#
# **Why route on every transfer.** Mux state belongs to the bus, not to a device. Between two
# transfers of one driver, another driver may have switched the mux to its own channel. So each
# transfer, under the bus lock, first writes the whole path and then transfers:
#
# ```mermaid
# sequenceDiagram
#     participant D as driver
#     participant C as I2CConnection
#     participant B as machine.I2C
#     D->>C: readfrom_mem(reg, n)
#     C->>C: take bus lock
#     C->>B: writeto(mux 0x70, 1 << ch)   (each hop, outermost first)
#     C->>B: readfrom_mem(addr, reg, n)
#     C->>C: release bus lock
#     C-->>D: bytes
# ```
#
# The path is **not** released after a transfer: the next transfer selects its own path anyway,
# and leaving the mux alone halves the traffic. `path_release` exists for the manager and for
# scans, which need everything downstream disconnected.
#
# **Used by:** `node.I2CNode` (every device and mux talks through one), the manager.
#
# **Not its job:** knowing what a device is (that is `node`), checking a path is valid (that is
# `routing`).
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `path_select` | write a one-hot channel mask to each mux on a path, outermost first |
# | `path_release` | deselect every mux on a path, innermost first |
# | `I2CConnection` | locked, routed transport for one device: `machine.I2C` without the address |

