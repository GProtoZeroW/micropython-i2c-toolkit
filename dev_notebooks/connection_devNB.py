# %% [markdown]
# ## `path_select` / `path_release`
# The two path operations, as plain functions of a bus so the manager and scans can use them
# without a connection. Both expect the caller to hold the bus lock.
#
# | Function | Order | Why that order |
# |---|---|---|
# | `path_select` | outermost first | a downstream mux is reachable only once its upstream mux has switched |
# | `path_release` | innermost first | deselecting the outer mux first would cut the inner one off before it is told to let go |
#
# Each mux gets a one-hot mask, `1 << channel`, which deselects every other channel on that mux.

# %%
# %%extract ../src/micropython_i2c/connection.py -a
def path_select(bus, path):
    """Write a one-hot channel mask to each mux on ``path``, outermost first.

    Each write must land before the next, since a downstream mux only becomes
    reachable once its upstream mux has switched. Call with the bus lock held.

    Args:
        bus: The ``machine.I2C`` object.
        path: Resolved hops as ``[[mux_addr, channel], ...]``.

    Raises:
        OSError: If a mux on the path does not acknowledge (absent, or unreachable).
    """
    for mux_addr, channel in path:
        bus.writeto(mux_addr, bytes([1 << channel]))


def path_release(bus, path):
    """Deselect every mux on ``path``, innermost first.

    Order matters: deselecting the outer mux first would cut the inner mux off the
    bus before it could be told to let go. Call with the bus lock held.

    Args:
        bus: The ``machine.I2C`` object.
        path: Resolved hops as ``[[mux_addr, channel], ...]``.

    Raises:
        OSError: If a mux on the path does not acknowledge.
    """
    for mux_addr, _ in reversed(path):
        bus.writeto(mux_addr, b"\x00")


