# ### validation/test: fixtures
# The registry, config and helper every check below uses. They are written to the test file
# too.
#
# Stand-in driver classes: the routing checks read only `ALLOWED_ADDRS`, `CHANNELS` and
# `addr_ok` from a driver class, so these carry just that, copied from the real drivers. A
# broken driver module then cannot break the routing tests. Their `__name__` is the real
# class name, because the channel message prints it.

# %%
# %%extract ../tests/test_routing.py -a
class StandInPart:
    """A driver class reduced to what ``RoutingTable`` reads."""

    ALLOWED_ADDRS = ()

    @classmethod
    def addr_ok(cls, addr):
        return addr in cls.ALLOWED_ADDRS


def stand_in(name, addrs, channels=None):
    """A ``StandInPart`` subclass called ``name``; a mux when ``channels`` is given."""
    attrs = {"ALLOWED_ADDRS": tuple(addrs)}
    if channels is not None:
        attrs["CHANNELS"] = channels
    return type(name, (StandInPart,), attrs)


