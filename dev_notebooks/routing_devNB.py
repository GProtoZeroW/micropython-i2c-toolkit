# %% [markdown]
# # Intent
# **Purpose:** turn the bench's wiring, written once as a config, into a checked table: which
# buses exist, where each mux sits, and the full route (bus, mux hops, address) to every
# device. The manager builds live objects from it; `scan_check` probes it.
#
# **Why it exists:** a wrong config shows up on the board as a NACK, a part answering for
# another, or a mux left open. Every one of those mistakes can be seen in the config itself, so
# `validate()` finds them all at once, before anything touches the bus.
#
# **What `validate()` checks, in order:**
#
# ```mermaid
# flowchart TD
#     A[mux references exist] --> B[buses declared]
#     B --> C[names unique]
#     C --> D[channels are ints >= 0]
#     D --> E{references OK?}
#     E -->|yes| F[path consistency]
#     F -->|consistent| G[address collisions]
#     D --> H{registry given?}
#     H -->|yes| I[driver exists, address legal]
#     I --> J[channel < mux CHANNELS, if references OK]
# ```
#
# Checks that need a sound topology are skipped when an earlier check found it unsound, so one
# typo does not produce a cascade of follow-on problems.
#
# **Segments and collisions.** A segment is `(bus, path)`: the parts that answer when exactly
# that path is selected. Selecting a path leaves every upstream segment connected too, so the
# parts visible on a segment are its own plus those of every prefix of its path. Two entries
# collide when they share an address and are visible together. Parts on sibling channels of
# one mux never are.
#
# | Path selected | Visible segments |
# |---|---|
# | `[]` | `[]` |
# | `[("mux_a", 3)]` | `[]`, `[("mux_a", 3)]` |
# | `[("mux_a", 3), ("mux_b", 0)]` | `[]`, `[("mux_a", 3)]`, `[("mux_a", 3), ("mux_b", 0)]` |
#
# **Used by:** `manager.I2CManager` and `manager.scan_check`, the bench config in `sim.bench`,
# `notebooks/03_routing_harness`.
#
# **Not its job:** talking to the bus, importing drivers (the caller passes the registry), or
# checking bus speeds (the manager does that).
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `ConfigError` | the error `validate()` raises, with every problem in `problems` |
# | `RoutingTable` | the parsed topology: `loads`, `from_dict`, the views `entries`, `resolve_path`, `segments`, and `validate` |

