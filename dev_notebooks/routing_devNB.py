# ## Parsing helpers
# `_parse_addr` accepts an address as an int, a `"0x.."` string, or a decimal string, so a
# config can use whatever the datasheet uses. JSON has no hex literals, hence the strings.

# %%
# %%extract ../src/micropython_i2c/routing.py -a
def _parse_addr(value):
    if isinstance(value, str):
        return int(value, 16) if value.lower().startswith("0x") else int(value)
    return value


# %% [markdown]
# `_parse_path` turns the JSON hops (`[["mux_a", 3]]`, lists because JSON has no tuples) into
# `(name, channel)` tuples, so a path can be a dict key in `segments()`. A missing or `null`
# path is the root segment, `[]`.

# %%
# %%extract ../src/micropython_i2c/routing.py -a
def _parse_path(path):
    return [(hop[0], hop[1]) for hop in path or ()]


