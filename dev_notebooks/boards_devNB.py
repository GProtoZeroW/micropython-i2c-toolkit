# %% [markdown]
# ## `board_get`
# Everything that takes a board accepts either its `BOARDS` name or the dict itself, so a test
# or the simulation can pass a board that is not in `BOARDS`.

# %%
# %%extract ../src/micropython_i2c/boards.py -a
def board_get(board):
    """Return a board dict, given either a ``BOARDS`` key or the dict itself.

    Raises:
        ValueError: If ``board`` is a name not in ``BOARDS``.
    """
    if isinstance(board, dict):
        return board
    try:
        return BOARDS[board]
    except KeyError:
        raise ValueError("unknown board {!r}; known: {}".format(board, sorted(BOARDS))) from None


