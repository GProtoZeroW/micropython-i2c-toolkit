def test_every_bus_has_pins_and_a_clock_cap():
    for name, board in BOARDS.items():
        for bus_id, cfg in board["buses"].items():
            assert {"scl", "sda", "baud_max"} <= set(cfg), (name, bus_id)
            assert 10_000 <= cfg["baud_max"] <= 1_000_000


# %% [markdown]
# ## `bus_open`
# A `machine.I2C` for one bus. `machine` is imported inside the function, so importing
# `boards` on the host works; calling `bus_open` there raises `ImportError`.

# %%
# %%extract ../src/micropython_i2c/boards.py -a
def bus_open(board, bus_id=0, freq=100_000):
    """Create the ``machine.I2C`` for ``bus_id`` on ``board`` (board only).

    Raises:
        ImportError: On the host, which has no ``machine`` module.
        KeyError: If the board has no bus ``bus_id``.
    """
    from machine import I2C, Pin

    cfg = board_get(board)["buses"][bus_id]
    return I2C(bus_id, scl=Pin(cfg["scl"]), sda=Pin(cfg["sda"]), freq=freq)


