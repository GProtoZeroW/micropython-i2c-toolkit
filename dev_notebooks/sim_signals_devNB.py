# %% [markdown]
# ## Stateful signals: `noisy` and `lag`
# `noisy` draws a fresh Gaussian sample on every read (a sensor's noise is per measurement), from
# its own seeded generator so a run repeats. `lag` is a first-order follower: between two reads
# `dt` apart it moves the fraction $1 - e^{-dt/\tau}$ of the way to the target. It works out the
# whole gap at once, so it is exact for a target that held still in between however rarely it is
# read. Reading at an earlier time than the last read (a new clock) starts it over.

# %%
# %%extract ../src/micropython_i2c/sim/signals.py -a
def noisy(signal, sigma, seed=0):
    """``signal`` plus Gaussian noise of standard deviation ``sigma``, seeded."""
    rng = random.Random(seed)

    def noisy_signal(t):
        return value(signal, t) + rng.gauss(0.0, value(sigma, t))

    return noisy_signal


def lag(target, tau_s, initial=None):
    """Follow ``target`` with a first-order lag of time constant ``tau_s`` seconds.

    Args:
        target: The value to follow (a plain value or a signal).
        tau_s: Time constant: after ``tau_s`` the output has covered 63 % of a step.
        initial: The output at the first read; default the target's value then.

    Raises:
        ValueError: If ``tau_s`` is not positive.
    """
    if tau_s <= 0:
        raise ValueError("lag: tau_s must be positive, got {}".format(tau_s))
    state = {"t": None, "y": None}

    def lagged(t):
        u = value(target, t)
        if state["t"] is None or t < state["t"]:  # first read, or a new clock: start over
            state["t"] = t
            state["y"] = u if initial is None else initial
            return state["y"]
        dt = t - state["t"]
        state["y"] += (u - state["y"]) * (1 - math.exp(-dt / tau_s))
        state["t"] = t
        return state["y"]

    return lagged


