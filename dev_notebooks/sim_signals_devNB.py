def ramp(start, end, t0_s, t1_s):
    """``start`` until ``t0_s``, a straight line to ``end`` at ``t1_s``, then ``end``.

    Raises:
        ValueError: If ``t1_s`` is not after ``t0_s``.
    """
    if t1_s <= t0_s:
        raise ValueError("ramp: t1_s ({}) must be after t0_s ({})".format(t1_s, t0_s))

    def signal(t):
        a, b = value(start, t), value(end, t)
        if t <= t0_s:
            return a
        if t >= t1_s:
            return b
        return a + (b - a) * (t - t0_s) / (t1_s - t0_s)

    return signal


def step(before, after, at_s):
    """``before`` until ``at_s``, then ``after``."""

    def signal(t):
        return value(after if t >= at_s else before, t)

    return signal


def sine(mean, amplitude, period_s, phase_s=0.0):
    """``mean + amplitude * sin(2 pi (t - phase_s) / period_s)``.

    Raises:
        ValueError: If ``period_s`` is not positive.
    """
    if period_s <= 0:
        raise ValueError("sine: period_s must be positive, got {}".format(period_s))

    def signal(t):
        return value(mean, t) + value(amplitude, t) * math.sin(
            2 * math.pi * (t - phase_s) / period_s
        )

    return signal


def sequence(points):
    """Straight lines through ``[(t_s, value), ...]``; flat before the first and after the last.

    Raises:
        ValueError: If there are no points, or the times do not increase.
    """
    pts = list(points)
    if not pts:
        raise ValueError("sequence: needs at least one (t_s, value) point")
    for (ta, _), (tb, _) in zip(pts, pts[1:]):
        if tb <= ta:
            raise ValueError("sequence: times must increase, got {} then {}".format(ta, tb))

    def signal(t):
        if t <= pts[0][0]:
            return value(pts[0][1], t)
        for (ta, va), (tb, vb) in zip(pts, pts[1:]):
            if t <= tb:
                a, b = value(va, t), value(vb, t)
                return a + (b - a) * (t - ta) / (tb - ta)
        return value(pts[-1][1], t)

    return signal


