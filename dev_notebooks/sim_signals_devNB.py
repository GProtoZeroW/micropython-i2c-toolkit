# %% [markdown]
# ## `now_s` and `value`
# `now_s` reads the installed clock, so a signal sees simulated time inside `with SimClock()`
# and real time (seconds since import) outside. `value` is what every fake calls: it is the one
# place that knows a quantity may be a signal.

# %%
# %%extract ../src/micropython_i2c/sim/signals.py -a
def now_s():
    """The current time in seconds, on the clock ``compat`` uses."""
    return ticks_us() / 1_000_000


def value(x, t_s=None):
    """``x`` at time ``t_s`` (default ``now_s()``).

    Args:
        x: A plain value, a signal (any callable ``f(t_s)``), or a tuple/list of either.
        t_s: The time to evaluate at; ``None`` means now.

    Returns:
        ``x`` itself if it is a plain value, ``x(t_s)`` if it is a signal, and a tuple/list of
        the resolved items if it is a tuple/list.
    """
    if t_s is None:
        t_s = now_s()
    if callable(x):
        return x(t_s)
    if isinstance(x, (tuple, list)):
        return type(x)(value(item, t_s) for item in x)
    return x


