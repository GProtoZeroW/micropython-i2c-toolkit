# # Intent
# **Purpose:** talk to a TI TMP102 temperature sensor in degrees Celsius: read it, set its
# ALERT thresholds and configuration, and take one-shot readings.
#
# **Why it exists:** the TMP102's words are left-justified two's complement whose width depends
# on a config bit (extended mode), and its config register has three kinds of bits that cannot
# read back as written. Getting either wrong gives numbers that look plausible and are wrong.
#
# **Used by:** the routing table and manager (`"driver": "TMP102"`), bring-up notebooks, and the
# bench (TMP102 on mux channel 2).
#
# **Not its job:** reaching the part (the `I2CConnection` does addressing, mux routing and
# locking) or register plumbing (`RegisterI2CBase` does caching and verified writes).
#
# ```python
# tmp = TMP102(I2CConnection(bus, 0x48, [[0x70, 2]], lock))
# tmp.temperature()                 # 23.4375
# tmp.limits_set(20.0, 30.0)        # (20.0, 30.0)
# ```
#
# ```mermaid
# classDiagram
#     RegisterI2CBase <|-- TMP102Regs
#     I2CDevice <|-- TMP102Regs
#     TMP102Regs <|-- TMP102
#     class TMP102Regs { datasheet facts only }
#     class TMP102 { temperature(), limits, config properties, one_shot() }
# ```
#
# **Data format** (temperature, T_HIGH, T_LOW):
#
# | Mode | Value bits | Padding | Range | Wire word for 50 C |
# |---|---|---|---|---|
# | normal (EM=0) | top 12 | low 4 read 0 | -55 to +128 C | `0x3200` |
# | extended (EM=1) | top 13 | low 3 read 0 | -55 to +150 C | `0x1900` |
#
# One LSB is $0.0625\,^\circ\mathrm{C}$ in both modes:
# $T = \mathrm{sign\_extend}(w \gg s,\ b) \times 0.0625$, with $(s, b) = (4, 12)$ or $(3, 13)$.
#
# ## What the module defines
#
# | Name | What it is |
# |---|---|
# | `TMP102Regs` | datasheet facts: addresses, registers, fields, verify masks, POR values, code tables |
# | `TMP102` | the driver: temperature, config properties, thresholds, one-shot |

