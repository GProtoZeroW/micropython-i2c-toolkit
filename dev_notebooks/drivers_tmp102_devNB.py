# %% [markdown]
# ### When does the temperature word switch to 13-bit?
#
# Notebook-only: turns extended mode on, then reads the raw temperature word every 10 ms for about
# half a second and prints each change with its time, decoded both ways. If the first words are
# still 12-bit data (with the EM indicator D0 already 1) and the format only changes at the next
# conversion, that is the lag the driver waits out. Measured 2026-11-13: old format at 5 ms, new at 61 ms.
#
# **What to do:** keep your fingers off the sensor (the temperature must stay steady).

# %%
regs = on_board(TMP102Regs)  # register level: the driver would wait out the lag
try:
    print("conversion rate: 4 Hz (power-on)")
    t0 = ticks_ms()
    regs.field_set(regs.REG_CONFIG, regs.F_EM, 1)
    seen = []
    for _ in range(50):  # about 500 ms, two conversions at 4 Hz
        seen.append((ticks_diff(ticks_ms(), t0), regs.reg_read(regs.REG_TEMP)))
        sleep_ms(10)
    prev = None
    for ms, raw in seen:
        if raw != prev:  # print only when the word changes
            print(
                "{:4d} ms  {:#06x}  D0={}  as 12-bit {:8.4f} C  as 13-bit {:8.4f} C".format(
                    ms,
                    raw,
                    raw & 1,
                    TMP102.celsius_from_raw(raw, False),
                    TMP102.celsius_from_raw(raw, True),
                )
            )
            prev = raw
finally:
    restore(regs)

