# %% [markdown]
# ## `TMP102`
# Interpretation on top of `TMP102Regs`: degrees in and out, named config settings, thresholds
# and one-shot.
#
# Extended mode changes how every temperature word decodes, so the driver caches it in `em` and
# resyncs it on construction and after every config write. A stale flag is silent: a 13-bit word
# decoded as 12-bit reads exactly half the true value.
#
# One-shot is the one place the driver writes raw: OS is a handshake, excluded from the verify
# mask, so a managed write cannot check it.


# %%
# %%extract ../src/micropython_i2c/drivers/tmp102.py -a
class TMP102(TMP102Regs):
    """TMP102 driver: temperature in C, config properties, thresholds, one-shot.

    Extended mode changes how every temperature word decodes, so it is cached in
    ``self.em`` and resynced on construction and after every config write. A stale flag
    is silent: a 13-bit word decoded as 12-bit reads exactly half the true value.
    ``mode_refresh()`` resyncs after something outside the driver touched the part.

    Changing EM has a second trap, measured on the part: D0 of the temperature word follows
    EM at once, but the data keeps the old format until the next conversion (61 ms at 4 Hz).
    Decoding it in the new format reads half or double the true value. So after a write
    that changes EM the driver waits one conversion period plus the maximum conversion time
    before returning (about 285 ms at 4 Hz). In shutdown nothing converts until a one-shot,
    so ``temperature()`` refuses to decode until ``one_shot()`` has run.

    The TMP102 has no ID register. The strongest identification available is the
    read-only R1/R0 bits, which always read ``11``.

    Attributes:
        em: True in extended (13-bit) mode, as last read from the part.
        format_stale: True after EM changed in shutdown, until the next ``one_shot()``.
    """

    def __init__(self, conn, **kwargs):
        super().__init__(conn, **kwargs)
        self.em = False
        self.format_stale = False
        self.mode_refresh()

    # Codecs: classmethods with an explicit ``em`` so they test without a device.

    @staticmethod
    def _format(em):
        """(shift, bits) of the left-justified word in the given mode."""
        return (3, 13) if em else (4, 12)

    @classmethod
    def celsius_from_raw(cls, word, em):
        """Decode a left-justified two's-complement word into degrees C."""
        shift, bits = cls._format(em)
        return cls.sign_extend(word >> shift, bits) * cls.LSB_C

    @classmethod
    def celsius_to_raw(cls, celsius, em):
        """Encode degrees C into a left-justified word, rounding half away from zero.

        Two bounds apply: the register width (what can be represented) and the part's
        operating range (what is meaningful). In extended mode the second is tighter,
        so checking only width would accept a 200 C threshold the part can never reach.

        Raises:
            ValueError: If either bound is exceeded.
        """
        shift, bits = cls._format(em)
        counts = int(celsius / cls.LSB_C + (0.5 if celsius >= 0 else -0.5))
        lo, hi = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
        if not lo <= counts <= hi:
            raise ValueError(
                "{} C not representable in {}-bit mode ({:.4f} to {:.4f} C)".format(
                    celsius, bits, lo * cls.LSB_C, hi * cls.LSB_C
                )
            )
        if not cls.TEMP_MIN <= celsius <= cls.TEMP_MAX:
            raise ValueError(
                "{} C outside the operating range ({} to {} C)".format(
                    celsius, cls.TEMP_MIN, cls.TEMP_MAX
                )
            )
        return (counts & ((1 << bits) - 1)) << shift

    # Temperature. Raw reads only: the temperature register must never be cached.

    def temperature(self):
        """Most recent conversion in degrees C.

        Raises:
            RuntimeError: If EM changed while in shutdown and no one-shot has run since: the
                register still holds a word in the old format.
        """
        if self.format_stale:
            raise RuntimeError(
                "extended mode changed in shutdown: the temperature register keeps the old "
                "format until the next conversion; take a one_shot() first"
            )
        return self.celsius_from_raw(self.reg_read(self.REG_TEMP), self.em)

    def temperature_raw(self):
        """The undecoded 16-bit temperature word."""
        return self.reg_read(self.REG_TEMP)

    # Configuration.

    def config_get(self, refresh=True):
        """The config register. Fresh by default: OS and AL are live status bits."""
        return self.reg_get(self.REG_CONFIG, refresh=refresh)

    def _em_resync(self):
        """Update ``em`` from the confirmed config value; if it changed, settle the format."""
        cfg = self.cached(self.REG_CONFIG)
        old, self.em = self.em, bool(self.field_extract(cfg, self.F_EM))
        if self.em == old:
            return
        if self.field_extract(cfg, self.F_SD):
            self.format_stale = True  # no conversion until a one-shot
            return
        self.format_stale = False
        rate = self.CONV_RATES[self.field_extract(cfg, self.F_CR)]
        sleep_ms(int(1000 / rate) + self.CONV_TIME_MAX_MS)  # the next conversion has run

    def config_set(self, value):
        """Write the whole config register (verified) and resync EM."""
        result = self.reg_set(self.REG_CONFIG, value)
        self._em_resync()
        return result

    def config_field_set(self, field, value):
        """Write one config field (verified) and resync EM."""
        result = self.field_set(self.REG_CONFIG, field, value)
        self._em_resync()
        return result

    def config_reset(self):
        """Restore the config register to its power-on value."""
        return self.config_set(self.CFG_POR)

    def mode_refresh(self):
        """Re-read EM from the device. Returns the new value."""
        self.em = self.flag_get(self.REG_CONFIG, self.F_EM)
        return self.em

    @property
    def extended_mode(self):
        """13-bit mode, allowing readings above 128 C.

        Setting it waits for the data to take the new format (see the class docstring). The
        thresholds are stored as raw words, so their meaning changes with EM: set the limits
        again after changing it.
        """
        return self.em

    @extended_mode.setter
    def extended_mode(self, enable):
        self.config_field_set(self.F_EM, 1 if enable else 0)

    @property
    def shutdown(self):
        """Shutdown mode; halts conversions. Required before ``one_shot()``."""
        return self.flag_get(self.REG_CONFIG, self.F_SD)

    @shutdown.setter
    def shutdown(self, enable):
        self.config_field_set(self.F_SD, 1 if enable else 0)

    @property
    def conversion_rate(self):
        """Continuous conversion rate in Hz: 0.25, 1, 4 (default) or 8."""
        return self.coded_get(self.REG_CONFIG, self.F_CR, self.CONV_RATES)

    @conversion_rate.setter
    def conversion_rate(self, hz):
        self.coded_set(self.REG_CONFIG, self.F_CR, self.CONV_RATES, hz)

    @property
    def fault_queue(self):
        """Consecutive out-of-limit conversions before ALERT: 1, 2, 4 or 6."""
        return self.coded_get(self.REG_CONFIG, self.F_FQ, self.FAULT_QUEUE)

    @fault_queue.setter
    def fault_queue(self, faults):
        self.coded_set(self.REG_CONFIG, self.F_FQ, self.FAULT_QUEUE, faults)

    @property
    def thermostat_mode(self):
        """False = comparator mode, True = interrupt mode (ALERT latches)."""
        return self.flag_get(self.REG_CONFIG, self.F_TM)

    @thermostat_mode.setter
    def thermostat_mode(self, interrupt):
        self.config_field_set(self.F_TM, 1 if interrupt else 0)

    @property
    def alert_polarity_high(self):
        """False (default) = ALERT active low, True = active high."""
        return self.flag_get(self.REG_CONFIG, self.F_POL)

    @alert_polarity_high.setter
    def alert_polarity_high(self, active_high):
        self.config_field_set(self.F_POL, 1 if active_high else 0)

    @property
    def alert(self):
        """Raw AL bit. With POL=0 it reads 1 when NOT alerting; POL inverts this."""
        return self.flag_get(self.REG_CONFIG, self.F_AL)

    @property
    def conversion_ready(self):
        """OS bit: True when idle. Only meaningful in shutdown mode."""
        return self.flag_get(self.REG_CONFIG, self.F_OS)

    # Thresholds. Same format as the temperature register.

    def high_limit_get(self):
        """T_HIGH in degrees C (power-on 80 C)."""
        return self.celsius_from_raw(self.reg_read(self.REG_THIGH), self.em)

    def low_limit_get(self):
        """T_LOW in degrees C (power-on 75 C)."""
        return self.celsius_from_raw(self.reg_read(self.REG_TLOW), self.em)

    def _limit_set(self, reg, celsius):
        raw = self.celsius_to_raw(celsius, self.em)
        return self.celsius_from_raw(self.reg_set(reg, raw), self.em)

    def high_limit_set(self, celsius):
        """Set T_HIGH, verified exactly. Returns what landed (within half an LSB)."""
        return self._limit_set(self.REG_THIGH, celsius)

    def low_limit_set(self, celsius):
        """Set T_LOW, verified exactly. Keep it below T_HIGH; the part does not check."""
        return self._limit_set(self.REG_TLOW, celsius)

    def limits_set(self, low_c, high_c):
        """Set both thresholds, rejecting a crossed pair before any bus traffic."""
        if low_c >= high_c:
            raise ValueError("T_LOW ({}) must be below T_HIGH ({})".format(low_c, high_c))
        return self.low_limit_set(low_c), self.high_limit_set(high_c)

    def limits_reset(self):
        """Restore both thresholds to 75 C / 80 C."""
        self.reg_set(self.REG_TLOW, self.TLOW_POR)
        self.reg_set(self.REG_THIGH, self.THIGH_POR)

    # One-shot.

    def one_shot(self, timeout_ms=100):
        """Trigger one conversion from shutdown and return it in degrees C.

        Handshake: write OS=1, poll until OS reads 1 again, read the temperature. OS is
        excluded from verification, so this uses the raw write path.

        Raises:
            RuntimeError: If not in shutdown mode (a continuous-mode reading would be
                indistinguishable from a real one-shot), or on timeout.
        """
        cfg = self.config_get()
        if not cfg & self.field_mask(self.F_SD):
            raise RuntimeError("one_shot() requires shutdown mode; set .shutdown = True")

        os_bit = self.field_mask(self.F_OS)
        self.reg_write(self.REG_CONFIG, cfg | os_bit)
        deadline = ticks_add(ticks_ms(), timeout_ms)
        while not self.reg_read(self.REG_CONFIG) & os_bit:
            if ticks_diff(deadline, ticks_ms()) <= 0:
                raise RuntimeError("conversion timed out after {} ms".format(timeout_ms))
            sleep_ms(1)
        self.format_stale = False  # this conversion used the current format
        return self.temperature()


