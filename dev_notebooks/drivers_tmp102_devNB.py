# %% [markdown]
# A validator runs before any write: a refused value leaves the real register untouched.
#
# **What to do:** nothing.

# %%


def under_100c(v):
    """Validator: refuse a raw threshold word above 100 C (0x6400)."""
    if v > 0x6400:
        raise ValueError("{:#06x} exceeds 100 C".format(v))


regs = on_board(TMP102Regs)
try:
    check_raises(
        "validator fires", ValueError, regs.reg_set, regs.REG_THIGH, 0x7000, validator=under_100c
    )
    check("threshold untouched", regs.reg_read(regs.REG_THIGH) == regs.THIGH_POR)
    check(
        "accepted value verifies on every bit",
        regs.reg_set(regs.REG_THIGH, 0x1E00, validator=under_100c) == 0x1E00,
    )
finally:
    restore(regs)

# %% [markdown]
# Tolerance: R1/R0 make the config read back differently from a request with them cleared, so
# the real difference is measured, then a tolerance just under it must fail and one equal to it
# must pass.
#
# **What to do:** nothing.

# %%
regs = on_board(TMP102Regs)
try:
    sabotaged = regs.CFG_POR & ~regs.field_mask(regs.F_RES)
    regs.reg_write(regs.REG_CONFIG, sabotaged)
    delta = abs(regs.reg_read(regs.REG_CONFIG) - sabotaged)
    check_raises(
        "tolerance just under fails",
        ValueError,
        regs.reg_set,
        regs.REG_CONFIG,
        sabotaged,
        tolerance=delta - 1,
    )
    landed = regs.reg_set(regs.REG_CONFIG, sabotaged, tolerance=delta)
    check(
        "tolerance equal to the delta passes",
        abs(landed - sabotaged) == delta,
        "delta {:#x}".format(delta),
    )
finally:
    restore(regs)

