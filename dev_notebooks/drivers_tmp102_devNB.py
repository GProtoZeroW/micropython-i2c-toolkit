# %% [markdown]
# ## `TMP102Regs`
# Every number here is from TI SBOS397I. The config register's verify mask leaves out the bits
# that cannot read back as written: OS reads inverted, R1/R0 (resolution) are read-only and
# always `11`, AL follows the comparator. The threshold registers have no such bits, so they
# have no mask entry and verify on every bit.


# %%
# %%extract ../src/micropython_i2c/drivers/tmp102.py -a
class TMP102Regs(RegisterI2CBase, I2CDevice):
    """Datasheet facts for the TMP102, with no driver logic."""

    ALLOWED_ADDRS = (0x48, 0x49, 0x4A, 0x4B)  # Table 6-4: ADD0 -> GND/V+/SDA/SCL
    BAUD_NOMINAL = 100_000
    BAUD_MAX = 400_000  # fast mode; HS mode needs a master code we cannot send
    BAUD_MIN = 10_000  # spec floor is ~1 kHz (SCL timeout); margin here

    BIG_ENDIAN = True
    REG_BYTES = 2

    # Pointer register values (Table 6-7). The pointer write is the same wire sequence
    # as a register read, so readfrom_mem works unmodified.
    REG_TEMP = 0x00  # read-only
    REG_CONFIG = 0x01
    REG_TLOW = 0x02
    REG_THIGH = 0x03

    # Config fields as (shift, width); byte 1 is the MSB (Tables 6-10/6-11).
    F_OS = (15, 1)  # one-shot / conversion ready
    F_RES = (13, 2)  # resolution, read-only, always 11
    F_FQ = (11, 2)  # fault queue
    F_POL = (10, 1)  # ALERT polarity
    F_TM = (9, 1)  # thermostat mode: 0 comparator, 1 interrupt
    F_SD = (8, 1)  # shutdown
    F_CR = (6, 2)  # conversion rate
    F_AL = (5, 1)  # alert status, read-only
    F_EM = (4, 1)  # extended mode

    # Config bits that cannot read back as written: OS reads inverted, R1/R0 are
    # read-only, AL is comparator-driven. The threshold registers have no such bits,
    # so they verify on every bit (no entry needed).
    CONFIG_VERIFY_MASK = 0xFFFF & ~(0x8000 | 0x6000 | 0x0020)
    VERIFY_MASKS = {REG_CONFIG: CONFIG_VERIFY_MASK}

    CFG_POR = 0x60A0
    THIGH_POR = 0x5000  # 80 C
    TLOW_POR = 0x4B00  # 75 C

    LSB_C = 0.0625
    TEMP_MIN = -55.0
    TEMP_MAX = 150.0  # extended-mode ceiling

    CONV_RATES = {0: 0.25, 1: 1.0, 2: 4.0, 3: 8.0}  # Hz, Table 6-5
    FAULT_QUEUE = {0: 1, 1: 2, 2: 4, 3: 6}  # Table 6-12
    CONV_TIME_MS = 26  # single conversion, typical (section 6.5; measured 29 ms incl. I2C)
    CONV_TIME_MAX_MS = 35  # single conversion, maximum


