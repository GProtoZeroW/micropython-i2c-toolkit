# # Intent
# **Purpose:** switch a SparkFun Qwiic Single Relay on and off over I2C, and read its state and
# firmware version.
#
# **Why it exists:** the relay board is an ATtiny with its own small command set, not a register
# map: a write of one byte is a command, and a state is read by sending the command byte and
# reading one byte back. The driver names the commands and always reads the state fresh from the
# board, so it never reports a cached state the relay is not in.
#
# **Used by:** the routing table and manager (`"driver": "QwiicRelay"`) and the bench (bus 0, the
# STEMMA QT connector, with the VL53L4CD).
#
# **Not its job:** the address-change command (`0x03`; the driver allows only the jumper
# addresses `0x18` and `0x19`), the multi-relay boards' commands, and anything wired to the
# contacts.
#
# ```python
# relay = QwiicRelay(I2CConnection(bus, 0x18, lock=bus_lock))
# relay.on()                 # command 0x01: close
# relay.state                # command 0x05, read one byte: True
# relay.toggle()             # read, flip, read back: False
# relay.state = True         # same as on()
# relay.firmware_version()   # command 0x04, read one byte
# ```
#
# | Command | Byte | Reply |
# |---|---|---|
# | relay off (open) | `0x00` | none |
# | relay on (closed) | `0x01` | none |
# | firmware version | `0x04` | one byte |
# | status | `0x05` | one byte, non-zero when closed |
