# %% [markdown]
# ### validation/test: in simulated time
# A thermostat: the relay switches a heater, and the room temperature is a `lag` signal (time
# constant 120 s) towards 30 C while the relay is closed and 18 C while it is open. The signal
# reads the fake's public `closed`. Inside `with SimClock() as clock:` a control loop reads the
# temperature every 5 simulated seconds and switches with the driver: on below 21.5 C, off above
# 22.5 C. An hour runs in a fraction of a second.
#
# This block has no matching hardware test: there is no heater on the bench.

# %% [markdown]
# Notebook-only: the thermostat loop, shared by the validation cell below. The unit test runs
# the same loop inline, so the test file needs nothing from here.


# %%
def thermostat(relay, temp, clock, minutes, on_below=21.5, off_above=22.5, every_s=5):
    """Run the control loop; returns ``[(t_s, temp_c, closed), ...]``, one per step."""
    log = []
    for _ in range(int(minutes * 60 / every_s)):
        t_c = value(temp)
        if t_c < on_below:
            relay.on()
        elif t_c > off_above:
            relay.off()
        log.append((clock.now_s(), t_c, relay.state))
        clock.advance(every_s)
    return log


# %% [markdown]
# #### validation: nominal usage
# One hour. The first 4 minutes are printed every 20 s (the warm-up and the first switching),
# then the range the temperature kept to after 10 minutes.

# %%
with SimClock() as clock:
    relay, part = on_fake()
    temp = lag(lambda t: 30.0 if part.closed else 18.0, tau_s=120, initial=18.0)
    log = thermostat(relay, temp, clock, minutes=60)
for t_s, t_c, closed in log[:48:4]:
    print("t = {:3.0f} s: {:5.2f} C, relay {}".format(t_s, t_c, "on" if closed else "off"))
late = [t_c for t_s, t_c, _ in log if t_s >= 600]
print("after 10 min: {:.2f} .. {:.2f} C | relay switched {} times".format(
    min(late), max(late), part.switches))  # fmt: skip

# %% [markdown]
# #### validation: anti-nominal usage
