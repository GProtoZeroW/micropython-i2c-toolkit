# %% [markdown]
# ## `QwiicRelay`
# The driver, ported unchanged. `on()` and `off()` write one command byte (`write_raw`); `state`
# and `firmware_version()` are one-byte "read byte" transfers with the command as the register
# (`reg_read`, 8-bit register, one byte). `state` is never cached: every read goes to the board.
# `toggle()` reads the state, writes the opposite, and returns the state read back.
#
# The address is `0x18`, or `0x19` with the ADR jumper closed. The firmware can be given another
# address by command; `ALLOWED_ADDRS` would then need widening. 100 kHz nominal, 400 kHz at most.
#
# No method raises on its own: a missing or silent board shows as the bus's `OSError`.


# %%
# %%extract ../../src/micropython_i2c/devices/drivers/qwiic_relay.py -a
class QwiicRelay(RegisterI2CBase, I2CDevice):
    """SparkFun Qwiic Single Relay: ``on()``, ``off()``, ``toggle()``, ``state``."""

    # 0x18 by default, 0x19 with the ADR jumper closed. The firmware can also be given
    # another address by command; widen this tuple if you do that.
    ALLOWED_ADDRS = (0x18, 0x19)
    BAUD_NOMINAL = 100_000
    BAUD_MAX = 400_000
    BAUD_MIN = 10_000

    REG_BYTES = 1

    CMD_OFF = 0x00
    CMD_ON = 0x01
    CMD_FIRMWARE_VERSION = 0x04
    CMD_STATUS = 0x05

    def on(self):
        """Close the relay."""
        self.write_raw(bytes([self.CMD_ON]))

    def off(self):
        """Open the relay."""
        self.write_raw(bytes([self.CMD_OFF]))

    @property
    def state(self):
        """True if the relay is closed. Always read fresh from the board."""
        return bool(self.reg_read(self.CMD_STATUS))

    @state.setter
    def state(self, closed):
        if closed:
            self.on()
        else:
            self.off()

    def toggle(self):
        """Flip the relay. Returns the new state as read back."""
        self.state = not self.state
        return self.state

    def firmware_version(self):
        """The firmware version byte."""
        return self.reg_read(self.CMD_FIRMWARE_VERSION)


