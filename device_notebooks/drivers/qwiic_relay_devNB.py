# %% [markdown]
# ## `FakeQwiicRelay`
# What it models, and where each behaviour comes from:
#
# | Behaviour | Source |
# |---|---|
# | a one-byte write is a command: `0x01` closes the relay, `0x00` opens it, any other command leaves it as it is | SparkFun Qwiic_Relay library (single relay) |
# | a "read byte" (`readfrom_mem`) with command `0x05` returns 1 when closed, 0 when open; with `0x04` the firmware version | SparkFun Qwiic_Relay library |
# | the same reply after a command write and a separate one-byte read | SparkFun Qwiic_Relay library: it writes the command, ends the transfer, then reads |
# | a read for any other command is refused (`OSError`) | the fake's choice: the firmware's reply is not documented |
#
# Not modelled: the address-change command (`0x03`), the relay's switching time and contact
# bounce, and the multi-relay boards' commands.
#
# Same behaviour as the old `micropython_i2c.fakes.FakeRelay`, plus the separate read and a
# `switches` count. The old fake raised `KeyError` for an unknown read; this one raises
# `OSError`, as a NACK would.


# %%
# %%extract ../../src/micropython_i2c/devices/drivers/qwiic_relay_fake.py -a
class FakeQwiicRelay:
    """SparkFun Qwiic Single Relay: one-byte commands, status read as a command byte.

    Args:
        version: The firmware version byte (command ``0x04``).

    Attributes:
        closed: True while the relay is closed (on). Public: signals may read it.
        version: The firmware version byte.
        switches: How many times the relay has changed state.
        command: The last command byte written (None before the first).
    """

    CMD_OFF = 0x00
    CMD_ON = 0x01
    CMD_FIRMWARE_VERSION = 0x04
    CMD_STATUS = 0x05

    def __init__(self, version=0x01):
        self.closed = False
        self.version = version
        self.switches = 0
        self.command = None

    def _reply(self, cmd):
        if cmd == self.CMD_STATUS:
            return int(self.closed)
        if cmd == self.CMD_FIRMWARE_VERSION:
            return self.version
        raise OSError(5, "EIO: no reply for command {}".format(cmd))

    def raw_write(self, data):
        self.command = data[0]
        if data[0] in (self.CMD_OFF, self.CMD_ON):
            closed = data[0] == self.CMD_ON
            if closed != self.closed:
                self.switches += 1
            self.closed = closed

    def raw_read(self, nbytes):
        return bytes([self._reply(self.command)]) * nbytes

    def mem_read(self, reg, nbytes):
        self.command = reg
        return bytes([self._reply(reg)]) * nbytes


